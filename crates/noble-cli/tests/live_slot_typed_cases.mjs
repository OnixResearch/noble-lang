#!/usr/bin/env node
/**
 * Typed live-case generation, slice one (issue #49): deterministic, well-typed *positive* cases
 * with expectations taken from a small declared table rather than from the production acceptance
 * routine, plus coverage counts by signature shape, nesting, repeated reborrow and effect
 * ceiling.
 *
 * Two stages stay separate: admission (install, candidate, publish) and runtime observation
 * (invoke). Nothing here mutates a premise, shrinks a witness or calls a legacy generator helper,
 * and no generated pass is presented as a live-slot theorem.
 */
import assert from 'node:assert/strict';
import { cli, selectedAuthority } from './live_slot_resource_ref_cli.mjs';

const QUOTE = String.fromCharCode(34);
const pure = 'LiveRef<I64,I64,pure>';
const emitting = 'LiveRef<I64,I64,live.dispatch+test.emit>';
const nested = `LiveRef<I64+${pure},I64,live.dispatch>`;
const seeded = (seed, bound) => {
  // A tiny deterministic LCG: the corpus order is reproducible from the seed alone.
  let state = seed >>> 0;
  const next = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state; };
  return Array.from({ length: bound }, () => next() % bound);
};
const seed = Number(process.env.NOBLE_LIVE_CASE_SEED ?? 20261027);
const order = seeded(seed, 8);

// Declared typing facts this slice generates from. A case is well typed only when the caller's
// forwarded reference type equals the target slot contract and the effect ceiling of every slot
// on the chain carries the leaf's declared effect.
const leafPrograms = {
  inert: { source: 'def inertLeaf [ drop 21 ]', name: 'inertLeaf', effect: null },
  emitting: { source: `def emittingLeaf [ drop ${QUOTE}x${QUOTE} test.emit drop 21 ]`, name: 'emittingLeaf', effect: 'test.emit' },
};
const refType = (inputs, outputs, ceiling) =>
  `LiveRef<${inputs.join('+')},${outputs.join('+')},${ceiling.join('+')}>`;
const shapes = [
  {
    shape: 'direct', nesting: 'single', callerSource: 'slot.invoke',
    // Slot A holds the leaf; slot B's caller forwards one reference to A. The nested chain shape
    // is not generated by this slice: its ordered forwarded-reference form needs the exact
    // fixture derivation, and an attempt at it is refused rather than silently mistyped.
    slots: [
      { slotId: 'A', role: 'leaf', input: ['I64'], output: ['I64'] },
      { slotId: 'B', role: 'caller', input: ['I64', 'leaf'], output: ['I64'] },
    ],
    refs: [{ position: 1, ordinal: 0, slot: 'A' }],
    publish: [['A', 'leaf'], ['B', 'callerA']],
  },
];
const ceilings = [
  { ceiling: 'pure', effects: ['live.dispatch'], leaf: 'inert' },
  { ceiling: 'dispatch+emit', effects: ['live.dispatch', 'test.emit'], leaf: 'emitting' },
];

// The expectation for one typed case, derived only from the table above.
const expected = oneCase => ({
  dispatches: oneCase.refs.length,
  effects: leafPrograms[oneCase.leaf].effect === null ? 0 : 1,
});

const runCase = async (binary, oneCase, ordinal) => {
  const variant = `typed-${oneCase.shape}-${oneCase.ceiling}-repeat${oneCase.repeat}-${ordinal}`;
  const emit = oneCase.effects.includes('test.emit');
  // Every slot on the chain carries the leaf's declared ceiling, and each forwarded reference's
  // declared (input, output, ceiling) equals the contract of the slot it names.
  // Resolve the symbolic formal names into concrete LiveRef types in publish order, so the
  // authority never sees an undeclared or cyclic nominal type.
  const resolved = {};
  // The caller's own ref formals carry the ceiling of the slot they name; a non-caller slot
  // forwards references and declares only the dispatch-only `pure` ceiling for them, as the
  // nested-roots fixture does.
  const resolve = formal => shift => direct => {
    if (formal === 'I64') return 'I64';
    const target = resolved[formal];
    assert.ok(target, `formal ${formal} used before its slot contract is resolved`);
    return refType(target.input, target.output, direct ? shift : ['pure']);
  };
  // A formal that names the slot being built is a reference to that slot itself, built from the
  // formals already resolved for it.
  const selfRef = (slot, inputs) => refType(inputs, slot.output, oneCase.effects);
  const contracts = [];
  for (const [slotId] of oneCase.publish) {
    const slot = oneCase.slots.find(row => row.slotId === slotId);
    const direct = slot.role === 'caller' || (slot.role === 'middle' && oneCase.shape === 'direct');
    const input = [];
    for (const formal of slot.input) {
      input.push(formal === slot.role
        ? selfRef(slot, input)
        : resolve(formal)(oneCase.effects)(slot.role === 'caller'));
    }
    const contract = { slotId, role: slot.role, input, output: slot.output };
    resolved[slot.role] = contract;
    contracts.push(contract);
  }
  const slots = contracts.map(contract => ({
    slotId: contract.slotId, input: contract.input, output: contract.output,
    effectCeiling: oneCase.effects, proofRequired: false,
  }));
  const projected = formal => resolve(formal)(oneCase.effects);
  // Each installed program needs its own selected host source identity, so the two live-slot
  // installs carry distinct ids over the same bytes, as the nested-roots lane does.
  const sources = {
    defLeaf: leafPrograms[oneCase.leaf].source,
    leaf: leafPrograms[oneCase.leaf].name,
    callerA: oneCase.callerSource,
  };
  const grants = slots.flatMap(slot => ['publish', 'dispatch', 'effect'].map(operation => ({
    operation, slotId: slot.slotId, allowed: !(operation === 'effect' && !emit),
  })));
  const session = await cli(binary, variant, selectedAuthority({
    sources, slots, grants, effects: oneCase.effects, quota: 32,
  }));
  const expectRow = (promise, outcome) => promise.then(row => {
    assert.equal(row.outcome, outcome, `${variant}: ${JSON.stringify(row).slice(0, 600)}`);
    return row;
  });
  try {
    await expectRow(session.configured, 'configured');
    await expectRow(session.issue({
      operation: 'define', id: 'defLeaf', name: leafPrograms[oneCase.leaf].name,
      source: leafPrograms[oneCase.leaf].source, inputs: [],
    }), 'definition-retained');
    await expectRow(session.issue({
      operation: 'install', id: 'leaf', source: leafPrograms[oneCase.leaf].name, inputs: ['I64'],
      selected_name: leafPrograms[oneCase.leaf].name,
    }), 'installed');
    await expectRow(session.issue({
      operation: 'install', id: 'callerA', source: oneCase.callerSource,
      inputs: resolved.caller.input,
    }), 'installed');
    await expectRow(session.issue({ operation: 'candidate', id: 'callerA' }), 'candidate-staged');
    let epoch = '0';
    for (const [slotId, program] of oneCase.publish) {
      const published = await expectRow(session.issue({
        operation: 'publish', slot: slotId, id: program, program_index: 0, expected_epoch: epoch,
      }), 'published');
      epoch = published.epoch;
    }
    const invoke = () => expectRow(session.issue({
      operation: 'invoke', id: 'callerA', inputs: [{ kind: 'i64', value: '5' }], refs: oneCase.refs,
    }), 'executed');
    const traces = [];
    for (let pass = 0; pass < oneCase.repeat; pass += 1) traces.push((await invoke()).request_trace);
    const observed = traces.map(trace => ({
      dispatches: trace.filter(row => row.operation === 'dispatch').length,
      effects: trace.filter(row => row.operation === 'effect').length,
      epochs: new Set(trace.filter(row => row.operation === 'dispatch')
        .map(row => row.policyInput.rootEpoch)).size,
    }));
    const wanted = expected(oneCase);
    for (const root of observed) {
      assert.equal(root.dispatches, wanted.dispatches,
        `${variant}: expected ${wanted.dispatches} dispatches, saw ${root.dispatches}`);
      assert.equal(root.effects, wanted.effects,
        `${variant}: expected ${wanted.effects} effects, saw ${root.effects}`);
      assert.equal(root.epochs, 1, `${variant}: one root must pin one map epoch`);
    }
    return { variant, admitted: true, shape: oneCase.shape, nesting: oneCase.nesting,
      ceiling: oneCase.ceiling, repeat: oneCase.repeat, observed };
  } finally {
    await session.close();
  }
};

export const run = async binary => {
  const cases = [];
  let cursor = 0;
  for (const shape of shapes) {
    for (const ceiling of ceilings) {
      for (const repeat of [1, 2]) {
        const chosen = order[cursor % order.length];
        cursor += 1;
        cases.push({
          shape: shape.shape, nesting: shape.nesting, callerSource: shape.callerSource,
          slots: shape.slots, refs: shape.refs, publish: shape.publish,
          ceiling: ceiling.ceiling, effects: ceiling.effects, leaf: ceiling.leaf, repeat, chosen,
        });
      }
    }
  }
  const results = [];
  for (const [ordinal, oneCase] of cases.entries()) {
    results.push(await runCase(binary, oneCase, ordinal));
  }
  const tally = (key, value) => results.filter(row => row[key] === value).length;
  const coverage = {
    admitted: results.filter(row => row.admitted).length,
    by_shape: Object.fromEntries(shapes.map(shape => [shape.shape, tally('shape', shape.shape)])),
    by_nesting: Object.fromEntries(['single'].map(nesting => [nesting, tally('nesting', nesting)])),
    by_ceiling: Object.fromEntries(ceilings.map(row => [row.ceiling, tally('ceiling', row.ceiling)])),
    by_repeated_reborrow: { once: tally('repeat', 1), twice: tally('repeat', 2) },
    total_dispatch_rows: results.reduce((total, row) =>
      total + row.observed.reduce((sum, root) => sum + root.dispatches, 0), 0),
    total_effect_rows: results.reduce((total, row) =>
      total + row.observed.reduce((sum, root) => sum + root.effects, 0), 0),
  };
  assert.equal(coverage.admitted, cases.length);
  assert.equal(coverage.by_shape.direct > 0, true);
  assert.equal(coverage.by_repeated_reborrow.once > 0 && coverage.by_repeated_reborrow.twice > 0, true);
  return {
    seed, case_digest: results.map(row => `${row.variant}:${row.observed.length}`).join(','),
    coverage,
    cases: results.map(row => ({ variant: row.variant, expected: row.observed })),
  };
};



/**
 * Controlled negative family (issue #49 item 4/5): mutate exactly one premise of the typed
 * direct-shape case and assert the *semantic refusal class* and the stage it is refused at, never
 * the incidental diagnostic wording. Each mutation leaves every other premise intact so the
 * failure stays attributable.
 *
 * The classes are declared here rather than read back from the production reports; the observed
 * diagnostics are returned for transparency only.
 */
const negativeMutations = [
  {
    class: 'binding-foreign-root',
    stage: 'command',
    // The caller has no formal that names slot X, so the reference cannot bind.
    mutate: oneCase => ({ ...oneCase, refs: [{ position: 1, ordinal: 0, slot: 'X' }] }),
  },
  {
    class: 'binding-wrong-position',
    stage: 'command',
    // The reference is bound at the value formal instead of the reference formal.
    mutate: oneCase => ({ ...oneCase, refs: [{ position: 0, ordinal: 0, slot: 'A' }] }),
  },
  {
    class: 'stack-incompatible',
    stage: 'command',
    // The invocation supplies a value the caller's first formal does not admit.
    mutate: oneCase => ({ ...oneCase, stack: [{ kind: 'bool', value: 'true' }] }),
  },
  {
    class: 'effect-not-granted',
    stage: 'slot',
    // Authority withholds the leaf's declared effect while the program still declares it.
    mutate: oneCase => ({ ...oneCase, denyEffect: true }),
  },
];

const runNegative = async (binary, oneCase, mutation, ordinal) => {
  const mutated = mutation.mutate(oneCase);
  const variant = `typed-negative-${mutation.class}-${ordinal}`;
  const emit = oneCase.effects.includes('test.emit');
  const contracts = [
    { slotId: 'A', input: ['I64'], output: ['I64'], effectCeiling: oneCase.effects, proofRequired: false },
    { slotId: 'B', input: ['I64', refType(['I64'], ['I64'], oneCase.effects)], output: ['I64'],
      effectCeiling: oneCase.effects, proofRequired: false },
  ];
  const grants = contracts.flatMap(slot => ['publish', 'dispatch', 'effect'].map(operation => ({
    operation, slotId: slot.slotId,
    allowed: !(operation === 'effect' && (!emit || (mutated.denyEffect === true && slot.slotId === 'A'))),
  })));
  const session = await cli(binary, variant, selectedAuthority({
    sources: { defLeaf: leafPrograms[oneCase.leaf].source, leaf: leafPrograms[oneCase.leaf].name,
      callerA: oneCase.callerSource },
    slots: contracts, grants, effects: oneCase.effects, quota: 32,
  }));
  const outcomes = [];
  try {
    outcomes.push(await session.configured);
    const issue = async request => { const row = await session.issue(request); outcomes.push(row); return row; };
    await issue({ operation: 'define', id: 'defLeaf', name: leafPrograms[oneCase.leaf].name,
      source: leafPrograms[oneCase.leaf].source, inputs: [] });
    await issue({ operation: 'install', id: 'leaf', source: leafPrograms[oneCase.leaf].name,
      inputs: ['I64'], selected_name: leafPrograms[oneCase.leaf].name });
    await issue({ operation: 'install', id: 'callerA', source: oneCase.callerSource,
      inputs: ['I64', refType(['I64'], ['I64'], oneCase.effects)] });
    await issue({ operation: 'candidate', id: 'callerA' });
    const leafEpoch = (await issue({ operation: 'publish', slot: 'A', id: 'leaf', program_index: 0,
      expected_epoch: '0' })).epoch;
    await issue({ operation: 'publish', slot: 'B', id: 'callerA', program_index: 0,
      expected_epoch: leafEpoch });
    const invoke = () => issue({ operation: 'invoke', id: 'callerA',
      inputs: mutated.stack ?? [{ kind: 'i64', value: '5' }], refs: mutated.refs });
    for (let pass = 0; pass < (mutated.repeat ?? oneCase.repeat); pass += 1) await invoke();
  } finally {
    await session.close();
  }
  // The mutation must be refused, and refused at the declared stage, without being folded into a
  // different class: the refusal of the mutated request itself is the one that matters.
  const refused = outcomes.filter(row => row.outcome === 'refused' || row.outcome === 'execution-failed');
  assert.ok(refused.length > 0, `${variant}: mutation must be refused, saw ${JSON.stringify(outcomes).slice(0, 600)}`);
  const matching = refused.filter(row => row.stage === mutation.stage);
  assert.ok(matching.length > 0,
    `${variant}: expected a refusal at stage ${mutation.stage}, saw ${JSON.stringify(refused).slice(0, 600)}`);
  return { variant, class: mutation.class, stage: mutation.stage, refused: matching.length,
    diagnostics: refused.map(row => row.diagnostic ?? row.outcome) };
};

export const runNegativeFamily = async (binary, positives) => {
  const oneCase = {
    shape: 'direct', nesting: 'single', callerSource: 'slot.invoke',
    ceiling: 'dispatch+emit', effects: ['live.dispatch', 'test.emit'], leaf: 'emitting', repeat: 1,
    refs: [{ position: 1, ordinal: 0, slot: 'A' }],
  };
  const results = [];
  for (const [ordinal, mutation] of negativeMutations.entries()) {
    results.push(await runNegative(binary, oneCase, mutation, ordinal));
  }
  assert.equal(results.length, negativeMutations.length);
  return {
    classes: results.map(row => row.class),
    by_stage: Object.fromEntries([...new Set(results.map(row => row.stage))]
      .map(stage => [stage, results.filter(row => row.stage === stage).length])),
    refused: results.reduce((total, row) => total + row.refused, 0),
    diagnostics: results.map(row => ({ class: row.class, observed: row.diagnostics })),
    positives_admitted: positives.admitted,
  };
};


/**
 * Failure-class-preserving minimization (issue #49 item 6). Each candidate shrinks one witness
 * dimension; a candidate is accepted only when the *same* declared class is still observed at the
 * same stage. A shrink that converts the failure into a different refusal class is rejected, and
 * for these four classes the starting witness is already minimal — which the report states rather
 * than implying a deep reduction happened.
 */
export const minimizeFamily = async (binary, oneCase, mutation, baseline) => {
  const candidates = [
    { dimension: 'repeat', value: 1 },
    { dimension: 'quota', value: 1 },
    { dimension: 'program_index', value: 0 },
  ];
  const accepted = [];
  const rejected = [];
  for (const candidate of candidates) {
    const attempt = { ...mutation, mutate: base => ({ ...mutation.mutate(base), [candidate.dimension]: candidate.value }) };
    const result = await runNegative(binary, oneCase, attempt, `${baseline.class}-${candidate.dimension}`);
    if (result.class === baseline.class && result.stage === baseline.stage) accepted.push(candidate.dimension);
    else rejected.push({ dimension: candidate.dimension, observed: result.class });
  }
  // "Minimal" here means the class survives every candidate shrink, so none of the witness
  // dimensions tried is load-bearing for it.
  return { class: baseline.class, accepted, rejected,
    minimal: accepted.length === candidates.length, starting_witness: mutation.class };
};

export const runMinimization = async (binary, fourCases) => {
  const oneCase = {
    shape: 'direct', nesting: 'single', callerSource: 'slot.invoke',
    ceiling: 'dispatch+emit', effects: ['live.dispatch', 'test.emit'], leaf: 'emitting', repeat: 1,
    refs: [{ position: 1, ordinal: 0, slot: 'A' }],
  };
  const results = [];
  for (const [ordinal, mutation] of negativeMutations.entries()) {
    results.push(await minimizeFamily(binary, oneCase, mutation,
      { class: mutation.class, stage: mutation.stage }));
  }
  return {
    classes: results.map(row => row.class),
    minimal_starting_witnesses: results.filter(row => row.minimal).length,
    accepted_shrinks: results.reduce((total, row) => total + row.accepted.length, 0),
    rejected_shrinks: results.flatMap(row => row.rejected),
    detail: results.map(row => ({ class: row.class, accepted: row.accepted, rejected: row.rejected })),
    negative_family_classes: fourCases.classes,
  };
};



/**
 * Bounded-budget boundary (issue #49 item 4): a genuinely reached retention
 * budget, not a synthetic one. `record: true` retains one frozen root per
 * executed invocation, and the CLI admits exactly the reviewed retention bound
 * and then refuses at the command stage. The bound is declared here, not read
 * back from the production report, and the refusal wording is reported for
 * transparency only.
 */
const retentionBound = 128;

const runRetentionFamily = async binary => {
  const QUOTE = String.fromCharCode(34);
  const defSource = `def traced [ drop ${QUOTE}A${QUOTE} test.emit drop 42 ]`;
  const effects = ['live.dispatch', 'test.emit'];
  const callerInput = refType(['I64'], ['I64'], effects);
  const slots = [
    { slotId: 'emit', input: ['I64'], output: ['I64'], effectCeiling: effects, proofRequired: false },
    { slotId: 'caller', input: ['I64', callerInput], output: ['I64'], effectCeiling: effects, proofRequired: false },
  ];
  const grants = slots.flatMap(slot => ['publish', 'dispatch', 'effect'].map(operation => (
    { operation, slotId: slot.slotId, allowed: true })));
  const session = await cli(binary, 'typed-retention', selectedAuthority({
    sources: { definition: defSource, named: 'traced', caller: 'slot.invoke' },
    slots, grants, effects, quota: 32,
  }));
  const seen = [];
  try {
    await session.configured;
    const issue = async request => { const row = await session.issue(request); seen.push(row); return row; };
    await issue({ operation: 'install', id: 'caller', source: 'slot.invoke', inputs: ['I64', callerInput] });
    await issue({ operation: 'define', id: 'definition', name: 'traced', source: defSource, inputs: [] });
    await issue({ operation: 'install', id: 'named', source: 'traced', inputs: ['I64'], selected_name: 'traced' });
    await issue({ operation: 'publish', slot: 'emit', id: 'named', program_index: 0, expected_epoch: '0' });
    let retained = 0;
    let refusal = null;
    for (let pass = 0; pass <= retentionBound; pass += 1) {
      const row = await issue({ operation: 'invoke', id: 'caller',
        inputs: [{ kind: 'i64', value: '5' }],
        refs: [{ position: 1, ordinal: 0, slot: 'emit' }], record: true });
      if (row.outcome === 'executed') { retained += 1; continue; }
      refusal = { pass, stage: row.stage, outcome: row.outcome, diagnostic: row.diagnostic };
      break;
    }
    assert.equal(retained, retentionBound,
      `the retention bound must admit exactly ${retentionBound} recorded roots, saw ${retained}`);
    assert.ok(refusal, 'the invocation past the retention bound must be refused, not executed');
    assert.equal(refusal.outcome, 'refused');
    assert.equal(refusal.stage, 'command');
    assert.equal(refusal.pass, retentionBound);
    // An over-budget request is a refusal, never an executed root that quietly
    // stopped being retained.
    assert.equal(seen.filter(row => row.outcome === 'executed').length, retentionBound);
    return { bound: retentionBound, retained, refusal_stage: refusal.stage,
      observed_diagnostic: refusal.diagnostic };
  } finally {
    await session.close();
  }
};



/**
 * Declared type boundaries (issue #49 item 4, type half). Each boundary is a
 * pair: the last admitted width/depth configures, the next one is refused at
 * the authority stage. Both numbers are declared here from the measured
 * boundary, and the refusal wording is reported for transparency only.
 */
const typeStackBound = 128;
const constructorNestingBound = 31;

const nestedLiveRef = depth => {
  let ty = 'I64';
  for (let level = 0; level < depth; level += 1) ty = refType([ty], ['I64'], ['live.dispatch']);
  return ty;
};

const configureAttempt = async (binary, variant, slotInput) => {
  const session = await cli(binary, variant, selectedAuthority({
    sources: { caller: 'slot.invoke' },
    slots: [{ slotId: 'wide', input: slotInput, output: ['I64'],
      effectCeiling: ['live.dispatch'], proofRequired: false }],
    grants: [], effects: ['live.dispatch'], quota: 8,
  }));
  try {
    const configured = await session.configured;
    return { variant, outcome: configured.outcome, stage: configured.stage,
      diagnostic: configured.diagnostic };
  } finally {
    await session.close();
  }
};

const runTypeBoundaryFamily = async binary => {
  const wide = width => Array.from({ length: width }, () => 'I64');
  const observations = [
    await configureAttempt(binary, 'type-stack-admitted', wide(typeStackBound)),
    await configureAttempt(binary, 'type-stack-refused', wide(typeStackBound + 1)),
    await configureAttempt(binary, 'nesting-admitted', [nestedLiveRef(constructorNestingBound)]),
    await configureAttempt(binary, 'nesting-refused', [nestedLiveRef(constructorNestingBound + 1)]),
  ];
  const [admittedStack, refusedStack, admittedNesting, refusedNesting] = observations;
  assert.equal(admittedStack.outcome, 'configured',
    `${JSON.stringify(admittedStack)}: a ${typeStackBound}-type stack must configure`);
  assert.equal(refusedStack.outcome, 'refused',
    `${JSON.stringify(refusedStack)}: a ${typeStackBound + 1}-type stack must be refused`);
  assert.equal(refusedStack.stage, 'authority');
  assert.equal(admittedNesting.outcome, 'configured',
    `${JSON.stringify(admittedNesting)}: nest depth ${constructorNestingBound} must configure`);
  assert.equal(refusedNesting.outcome, 'refused',
    `${JSON.stringify(refusedNesting)}: nest depth ${constructorNestingBound + 1} must be refused`);
  assert.equal(refusedNesting.stage, 'authority');
  // The admitted side never becomes a refusal and the refused side never
  // configures: a boundary pair, not two independent observations.
  return {
    stack: { admitted: typeStackBound, refused_first: typeStackBound + 1 },
    nesting: { admitted: constructorNestingBound, refused_first: constructorNestingBound + 1 },
    refusal_stage: 'authority',
    observed_diagnostics: [refusedStack.diagnostic, refusedNesting.diagnostic],
  };
};

if (process.argv[1]?.endsWith('live_slot_typed_cases.mjs') === true) {
  const positives = await run(process.argv[2]);
  const negative = await runNegativeFamily(process.argv[2], positives);
  const minimization = await runMinimization(process.argv[2], negative);
  const retention = await runRetentionFamily(process.argv[2]);
  const typeBoundaries = await runTypeBoundaryFamily(process.argv[2]);
  process.stdout.write(`${JSON.stringify({ ...positives, negative, minimization, retention,
    typeBoundaries })}\n`);
}
