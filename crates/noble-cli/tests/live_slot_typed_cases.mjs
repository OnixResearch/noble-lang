#!/usr/bin/env node
/**
 * Typed live-case generation, slice one (issue #49): deterministic, well-typed *positive* cases
 * with expectations taken from a small declared table rather than from the production acceptance
 * routine, plus coverage counts by signature shape, nesting, repeated reborrow and effect
 * ceiling.
 *
 * Two stages stay separate: admission (install, candidate, publish) and runtime observation
 * (invoke). Nothing here mutates a premise, shrinks a witness or calls a legacy generator helper,
 * and no generated pass is presented as a live-slot theorem.
 */
import assert from 'node:assert/strict';
import { cli, selectedAuthority } from './live_slot_resource_ref_cli.mjs';

const QUOTE = String.fromCharCode(34);
const pure = 'LiveRef<I64,I64,pure>';
const emitting = 'LiveRef<I64,I64,live.dispatch+test.emit>';
const nested = `LiveRef<I64+${pure},I64,live.dispatch>`;
const seeded = (seed, bound) => {
  // A tiny deterministic LCG: the corpus order is reproducible from the seed alone.
  let state = seed >>> 0;
  const next = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state; };
  return Array.from({ length: bound }, () => next() % bound);
};
const seed = Number(process.env.NOBLE_LIVE_CASE_SEED ?? 20261027);
const order = seeded(seed, 8);

// Declared typing facts this slice generates from. A case is well typed only when the caller's
// forwarded reference type equals the target slot contract and the effect ceiling of every slot
// on the chain carries the leaf's declared effect.
const leafPrograms = {
  inert: { source: 'def inertLeaf [ drop 21 ]', name: 'inertLeaf', effect: null },
  emitting: { source: `def emittingLeaf [ drop ${QUOTE}x${QUOTE} test.emit drop 21 ]`, name: 'emittingLeaf', effect: 'test.emit' },
};
const refType = (inputs, outputs, ceiling) =>
  `LiveRef<${inputs.join('+')},${outputs.join('+')},${ceiling.join('+')}>`;
const shapes = [
  {
    shape: 'direct', nesting: 'single', callerSource: 'slot.invoke',
    // Slot A holds the leaf; slot B's caller forwards one reference to A. The nested chain shape
    // is not generated by this slice: its ordered forwarded-reference form needs the exact
    // fixture derivation, and an attempt at it is refused rather than silently mistyped.
    slots: [
      { slotId: 'A', role: 'leaf', input: ['I64'], output: ['I64'] },
      { slotId: 'B', role: 'caller', input: ['I64', 'leaf'], output: ['I64'] },
    ],
    refs: [{ position: 1, ordinal: 0, slot: 'A' }],
    publish: [['A', 'leaf'], ['B', 'callerA']],
  },
];
const ceilings = [
  { ceiling: 'pure', effects: ['live.dispatch'], leaf: 'inert' },
  { ceiling: 'dispatch+emit', effects: ['live.dispatch', 'test.emit'], leaf: 'emitting' },
];

// The expectation for one typed case, derived only from the table above.
const expected = oneCase => ({
  dispatches: oneCase.refs.length,
  effects: leafPrograms[oneCase.leaf].effect === null ? 0 : 1,
});

const runCase = async (binary, oneCase, ordinal) => {
  const variant = `typed-${oneCase.shape}-${oneCase.ceiling}-repeat${oneCase.repeat}-${ordinal}`;
  const emit = oneCase.effects.includes('test.emit');
  // Every slot on the chain carries the leaf's declared ceiling, and each forwarded reference's
  // declared (input, output, ceiling) equals the contract of the slot it names.
  // Resolve the symbolic formal names into concrete LiveRef types in publish order, so the
  // authority never sees an undeclared or cyclic nominal type.
  const resolved = {};
  // The caller's own ref formals carry the ceiling of the slot they name; a non-caller slot
  // forwards references and declares only the dispatch-only `pure` ceiling for them, as the
  // nested-roots fixture does.
  const resolve = formal => shift => direct => {
    if (formal === 'I64') return 'I64';
    const target = resolved[formal];
    assert.ok(target, `formal ${formal} used before its slot contract is resolved`);
    return refType(target.input, target.output, direct ? shift : ['pure']);
  };
  // A formal that names the slot being built is a reference to that slot itself, built from the
  // formals already resolved for it.
  const selfRef = (slot, inputs) => refType(inputs, slot.output, oneCase.effects);
  const contracts = [];
  for (const [slotId] of oneCase.publish) {
    const slot = oneCase.slots.find(row => row.slotId === slotId);
    const direct = slot.role === 'caller' || (slot.role === 'middle' && oneCase.shape === 'direct');
    const input = [];
    for (const formal of slot.input) {
      input.push(formal === slot.role
        ? selfRef(slot, input)
        : resolve(formal)(oneCase.effects)(slot.role === 'caller'));
    }
    const contract = { slotId, role: slot.role, input, output: slot.output };
    resolved[slot.role] = contract;
    contracts.push(contract);
  }
  const slots = contracts.map(contract => ({
    slotId: contract.slotId, input: contract.input, output: contract.output,
    effectCeiling: oneCase.effects, proofRequired: false,
  }));
  const projected = formal => resolve(formal)(oneCase.effects);
  // Each installed program needs its own selected host source identity, so the two live-slot
  // installs carry distinct ids over the same bytes, as the nested-roots lane does.
  const sources = {
    defLeaf: leafPrograms[oneCase.leaf].source,
    leaf: leafPrograms[oneCase.leaf].name,
    callerA: oneCase.callerSource,
  };
  const grants = slots.flatMap(slot => ['publish', 'dispatch', 'effect'].map(operation => ({
    operation, slotId: slot.slotId, allowed: !(operation === 'effect' && !emit),
  })));
  const session = await cli(binary, variant, selectedAuthority({
    sources, slots, grants, effects: oneCase.effects, quota: 32,
  }));
  const expectRow = (promise, outcome) => promise.then(row => {
    assert.equal(row.outcome, outcome, `${variant}: ${JSON.stringify(row).slice(0, 600)}`);
    return row;
  });
  try {
    await expectRow(session.configured, 'configured');
    await expectRow(session.issue({
      operation: 'define', id: 'defLeaf', name: leafPrograms[oneCase.leaf].name,
      source: leafPrograms[oneCase.leaf].source, inputs: [],
    }), 'definition-retained');
    await expectRow(session.issue({
      operation: 'install', id: 'leaf', source: leafPrograms[oneCase.leaf].name, inputs: ['I64'],
      selected_name: leafPrograms[oneCase.leaf].name,
    }), 'installed');
    await expectRow(session.issue({
      operation: 'install', id: 'callerA', source: oneCase.callerSource,
      inputs: resolved.caller.input,
    }), 'installed');
    await expectRow(session.issue({ operation: 'candidate', id: 'callerA' }), 'candidate-staged');
    let epoch = '0';
    for (const [slotId, program] of oneCase.publish) {
      const published = await expectRow(session.issue({
        operation: 'publish', slot: slotId, id: program, program_index: 0, expected_epoch: epoch,
      }), 'published');
      epoch = published.epoch;
    }
    const invoke = () => expectRow(session.issue({
      operation: 'invoke', id: 'callerA', inputs: [{ kind: 'i64', value: '5' }], refs: oneCase.refs,
    }), 'executed');
    const traces = [];
    for (let pass = 0; pass < oneCase.repeat; pass += 1) traces.push((await invoke()).request_trace);
    const observed = traces.map(trace => ({
      dispatches: trace.filter(row => row.operation === 'dispatch').length,
      effects: trace.filter(row => row.operation === 'effect').length,
      epochs: new Set(trace.filter(row => row.operation === 'dispatch')
        .map(row => row.policyInput.rootEpoch)).size,
    }));
    const wanted = expected(oneCase);
    for (const root of observed) {
      assert.equal(root.dispatches, wanted.dispatches,
        `${variant}: expected ${wanted.dispatches} dispatches, saw ${root.dispatches}`);
      assert.equal(root.effects, wanted.effects,
        `${variant}: expected ${wanted.effects} effects, saw ${root.effects}`);
      assert.equal(root.epochs, 1, `${variant}: one root must pin one map epoch`);
    }
    return { variant, admitted: true, shape: oneCase.shape, nesting: oneCase.nesting,
      ceiling: oneCase.ceiling, repeat: oneCase.repeat, observed };
  } finally {
    await session.close();
  }
};

export const run = async binary => {
  const cases = [];
  let cursor = 0;
  for (const shape of shapes) {
    for (const ceiling of ceilings) {
      for (const repeat of [1, 2]) {
        const chosen = order[cursor % order.length];
        cursor += 1;
        cases.push({
          shape: shape.shape, nesting: shape.nesting, callerSource: shape.callerSource,
          slots: shape.slots, refs: shape.refs, publish: shape.publish,
          ceiling: ceiling.ceiling, effects: ceiling.effects, leaf: ceiling.leaf, repeat, chosen,
        });
      }
    }
  }
  const results = [];
  for (const [ordinal, oneCase] of cases.entries()) {
    results.push(await runCase(binary, oneCase, ordinal));
  }
  const tally = (key, value) => results.filter(row => row[key] === value).length;
  const coverage = {
    admitted: results.filter(row => row.admitted).length,
    by_shape: Object.fromEntries(shapes.map(shape => [shape.shape, tally('shape', shape.shape)])),
    by_nesting: Object.fromEntries(['single'].map(nesting => [nesting, tally('nesting', nesting)])),
    by_ceiling: Object.fromEntries(ceilings.map(row => [row.ceiling, tally('ceiling', row.ceiling)])),
    by_repeated_reborrow: { once: tally('repeat', 1), twice: tally('repeat', 2) },
    total_dispatch_rows: results.reduce((total, row) =>
      total + row.observed.reduce((sum, root) => sum + root.dispatches, 0), 0),
    total_effect_rows: results.reduce((total, row) =>
      total + row.observed.reduce((sum, root) => sum + root.effects, 0), 0),
  };
  assert.equal(coverage.admitted, cases.length);
  assert.equal(coverage.by_shape.direct > 0, true);
  assert.equal(coverage.by_repeated_reborrow.once > 0 && coverage.by_repeated_reborrow.twice > 0, true);
  return {
    seed, case_digest: results.map(row => `${row.variant}:${row.observed.length}`).join(','),
    coverage,
    cases: results.map(row => ({ variant: row.variant, expected: row.observed })),
  };
};

if (process.argv[1]?.endsWith('live_slot_typed_cases.mjs') === true) {
  const summary = await run(process.argv[2]);
  process.stdout.write(`${JSON.stringify(summary)}\n`);
}
