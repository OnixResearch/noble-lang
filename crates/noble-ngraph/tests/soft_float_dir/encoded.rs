//! Two actual `ngraph-f32/0` encodings, parsed and checked by `noble-ngraph` and exported into the
//! certificate fragment of `NobleFoundation.Binary32.Checker` (issue #44). `Binary32CheckerEncoded.lean`
//! is generated from them; its header states what the kernel checks. Regenerate after a deliberate
//! change with `cargo test -p noble-ngraph --test soft_float -- --ignored write_the_lean_file`,
//! then rerun the foundation lane.

use noble_ngraph::check;
use noble_ngraph::format::graph;
use noble_ngraph::ir::{Graph, Literal, Op};

/// The generated file the foundation lane kernel-checks.
const COMMITTED: &str =
    include_str!("../../../../proofs/foundation/NobleFoundation/Binary32CheckerEncoded.lean");

/// `x · x + (-1)`: near `x = 1` the result cancels towards zero.
const CANCELLATION: &str = "ngraph-ir/0 ngraph-f32/0
subject authored-name certificate cancellation
slot input f32
%0 = input 0
%1 = f32.mul %0 %0
%2 = const f32 -1
%3 = f32.add %1 %2
out %3
";

/// `x · x`: over `[1, 2^63]` the square stays below the overflow limit, over `[1, 2^64]` it does not.
const SQUARE: &str = "ngraph-ir/0 ngraph-f32/0
subject authored-name certificate near overflow
slot input f32
%0 = input 0
%1 = f32.mul %0 %0
out %1
";

/// A checked node as a fragment `Node`; every operation outside the fragment is `outside`, as the
/// checker's own vocabulary has it.
fn node_term(op: &Op) -> String {
    match op {
        Op::Input(slot) => format!(".input {slot}"),
        Op::Const(Literal::F32(bits)) => format!(".const 0x{bits:08X}"),
        Op::F32Add(a, b) => format!(".add {} {}", a.0, b.0),
        Op::F32Mul(a, b) => format!(".mul {} {}", a.0, b.0),
        other => panic!("not expected in these fixtures: {other:?}"),
    }
}

/// The checked graph of one encoding, as a Lean `Graph` term.
fn graph_term(text: &str) -> String {
    let scheme = super::common::IDS;
    let parsed: Graph = graph::parse(&scheme, text).expect("the encoding parses");
    let checked = check::check(&scheme, parsed).expect("the encoding checks");
    let nodes: Vec<String> = checked
        .graph()
        .nodes
        .iter()
        .map(|node| node_term(&node.op))
        .collect();
    let outputs: Vec<String> = checked
        .graph()
        .outputs
        .iter()
        .map(|output| output.0.to_string())
        .collect();
    format!(
        "{{ nodes := [{}], outputs := [{}] }}",
        nodes.join(", "),
        outputs.join(", ")
    )
}

fn quoted(text: &str) -> String {
    text.lines().map(|line| format!("    {line}\n")).collect()
}

/// The whole generated Lean module.
fn lean_file() -> String {
    format!(
        "import NobleFoundation.Binary32Checker

/-!
# Certificates on actual encoded graphs (issue #44)

Generated by `crates/noble-ngraph/tests/soft_float_dir/encoded.rs`; do not edit by hand.
`the_lean_file_is_the_real_encoding` fails when the parsed and checked graphs change, until this
file is regenerated and the foundation lane rerun.

Each graph below is the node list `noble-ngraph` produces when it parses and checks an
`ngraph-f32/0` encoding, written in the checker's fragment. The kernel decides the checker on it
with the model's certificates, and `check_sound` turns each acceptance into the enclosure statement
for every applicable input. The cancellation encoding is

```text
{cancellation}```

and the near-overflow encoding is

```text
{square}```

Reading the checked `noble-ngraph` nodes as fragment nodes is the one trusted translation. Binding
these graphs' identities into a certificate context is not done here.
-/

namespace NobleFoundation.Binary32.Checker.Encoded

open NobleFoundation.Binary32 NobleFoundation.Binary32.Checker

/-- The checked graph of the cancellation encoding. -/
def cancellation : Graph := {cancellation_graph}

/-- The checked graph of the near-overflow encoding. -/
def square : Graph := {square_graph}

set_option maxRecDepth 100000 in
/-- **The cancellation bound holds on the encoded graph**: `x · x + (-1)` over `x ∈ [1, 2]`. -/
theorem cancellation_certified : check fixtureBudget cancellation cancellationCertificate = .certified := by
  decide +kernel

/-- Every applicable input's machine and real values are enclosed by the certified bounds. -/
theorem cancellation_sound (machine : List Bits) (real : List ℚ)
    (applies : Applies cancellationCertificate.domains machine real) :
    AllEnclose cancellationCertificate.bounds (machineValues machine cancellation)
      (realValues real cancellation) :=
  check_sound fixtureBudget cancellation cancellationCertificate cancellation_certified machine real
    applies

set_option maxRecDepth 100000 in
/-- **Near overflow on the encoded graph**: certified over `[1, 2^63]`, refused over `[1, 2^64]`. -/
theorem square_near_overflow :
    check fixtureBudget square (squareCertificate (2 ^ 63)) = .certified ∧
      check fixtureBudget square (squareCertificate (2 ^ 64)) = .unknown 1 := by
  decide +kernel

/-- Every applicable input's machine and real values are enclosed by the certified bounds. -/
theorem square_sound (machine : List Bits) (real : List ℚ)
    (applies : Applies (squareCertificate (2 ^ 63)).domains machine real) :
    AllEnclose (squareCertificate (2 ^ 63)).bounds (machineValues machine square)
      (realValues real square) :=
  check_sound fixtureBudget square (squareCertificate (2 ^ 63)) square_near_overflow.1 machine real
    applies

end NobleFoundation.Binary32.Checker.Encoded
",
        cancellation = quoted(CANCELLATION),
        square = quoted(SQUARE),
        cancellation_graph = graph_term(CANCELLATION),
        square_graph = graph_term(SQUARE),
    )
}

#[test]
fn the_lean_file_is_the_real_encoding() {
    assert!(
        lean_file() == COMMITTED,
        "the parsed graphs changed: regenerate Binary32CheckerEncoded.lean with `cargo test -p noble-ngraph --test soft_float -- --ignored write_the_lean_file` and rerun the foundation lane"
    );
}

#[test]
#[ignore = "writes proofs/foundation/NobleFoundation/Binary32CheckerEncoded.lean; run after a deliberate change"]
fn write_the_lean_file() {
    std::fs::write(
        concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../proofs/foundation/NobleFoundation/Binary32CheckerEncoded.lean"
        ),
        lean_file(),
    )
    .expect("generated file written");
}
