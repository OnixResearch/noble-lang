//! Pin the generated Lean corpus and a real noncanonical binary to the compiler's actual graph,
//! layout and stream, decoded after the binary round trip. No exporter-derived statement is a
//! general Rust-executor or Lean-to-Rust theorem (issue #129).

use noble_ngraph::check::CheckedGraph;
use noble_ngraph::ir::{Literal, Op};
use noble_ngraph::permutation::{self, Artifact};
use noble_ngraph::schedule::I64Instruction;
use noble_ngraph::sem::Value;

const BINARY: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../verification/ngraph/permutation-noncanonical-0.bin"
);
const LEAN: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../proofs/foundation/NobleFoundation/PackedPermutationCorpus.lean"
);

fn numbers(values: &[u32]) -> String {
    format!(
        "[{}]",
        values
            .iter()
            .map(u32::to_string)
            .collect::<Vec<_>>()
            .join(", ")
    )
}
fn words(values: &[String]) -> String {
    format!("\n  [{}]", values.join(",\n   "))
}
fn instruction(ins: I64Instruction) -> String {
    match ins {
        I64Instruction::Add(d, a, b) => format!(".add {d} {a} {b}"),
        I64Instruction::Sub(d, a, b) => format!(".sub {d} {a} {b}"),
        I64Instruction::Mul(d, a, b) => format!(".mul {d} {a} {b}"),
        I64Instruction::Eq(d, a, b) => format!(".eq {d} {a} {b}"),
        I64Instruction::Guard { .. } => panic!("guards are not part of the permutation profile"),
    }
}
fn node(op: &Op) -> String {
    match op {
        Op::Input(slot) => format!(".input {slot}"),
        Op::Const(Literal::I64(bits)) => format!(".constant 0x{:016X}", bits.cast_unsigned()),
        Op::I64Add(a, b) => format!(".add {} {}", a.0, b.0),
        Op::I64Sub(a, b) => format!(".sub {} {}", a.0, b.0),
        Op::I64Mul(a, b) => format!(".mul {} {}", a.0, b.0),
        Op::I64Eq(a, b) => format!(".eq {} {}", a.0, b.0),
        _ => panic!("graph outside total I64/Bool fragment"),
    }
}
fn call(name: &str, witness: &str, instrs: &str, preloads: &str, out_regs: &str) -> String {
    format!(
        "validate nodes regs nodeLayers layers {preloads} {witness} {instrs} outputs {out_regs}",
        witness = if witness.is_empty() {
            format!("{name}Witness")
        } else {
            witness.to_string()
        },
        instrs = if instrs.is_empty() {
            format!("{name}Instrs")
        } else {
            instrs.to_string()
        },
        preloads = if preloads.is_empty() {
            String::from("preloads")
        } else {
            preloads.to_string()
        },
        out_regs = if out_regs.is_empty() {
            String::from("outRegs")
        } else {
            out_regs.to_string()
        }
    )
}

fn corpus(checked: &CheckedGraph, artifacts: &[Artifact; 3]) -> String {
    let [canonical, first, second] = artifacts;
    let graph = checked.graph();
    let layout = &canonical.layout;
    let nodes = graph
        .nodes
        .iter()
        .map(|item| node(&item.op))
        .collect::<Vec<_>>();
    let regs = numbers(&layout.reg);
    let node_layers = numbers(
        &(0..graph.nodes.len())
            .map(|index| checked.layer(noble_ngraph::NodeId(index as u32)))
            .collect::<Vec<_>>(),
    );
    let layers = format!(
        "[{}]",
        layout
            .layers
            .iter()
            .map(|(start, end)| format!("({start}, {end})"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    // The real packed evaluator loads constants first and input slots next. Do not normalize
    // these producer-owned tables: the model must check the actual preload order and bindings.
    let mut preloads = layout
        .consts
        .iter()
        .map(|(reg, bits)| format!(".setConst {reg} 0x{bits:016X}"))
        .collect::<Vec<_>>();
    preloads.extend(
        layout
            .slot_regs
            .iter()
            .map(|(reg, slot)| format!(".setInput {reg} {slot}")),
    );
    let outputs = numbers(&graph.outputs.iter().map(|id| id.0).collect::<Vec<_>>());
    let out_regs = numbers(&canonical.output_regs);
    let mut source = format!(
        r#"import NobleFoundation.PackedPermutation

/-!
Generated by the existing schedule_correspondence test target from the actual checked graph,
compiler layout and instruction streams, after binary encode/decode. The source test rejects
artifact-byte or corpus drift. Model validity is kernel checked per artifact; no proof binds
arbitrary Rust execution, host decoding or Rust checker to the Lean model (issue #129).
-/
namespace NobleFoundation.PackedPermutationCorpus
open NobleFoundation.PackedSchedule
open NobleFoundation.PackedPermutation

def nodes : List Node := {nodes}
def regs : List Nat := {regs}
def nodeLayers : List Nat := {node_layers}
def layers : List (Nat × Nat) := {layers}
def preloads : List Instr := {preloads}
def outputs : List Nat := {outputs}
def outRegs : List Nat := {out_regs}
"#,
        nodes = words(&nodes),
        regs = regs,
        node_layers = node_layers,
        layers = layers,
        preloads = words(&preloads),
        outputs = outputs,
        out_regs = out_regs
    );
    for (name, artifact) in [
        ("canonical", canonical),
        ("first", first),
        ("second", second),
    ] {
        let actual = words(
            &artifact
                .stream
                .iter()
                .copied()
                .map(instruction)
                .collect::<Vec<_>>(),
        );
        source.push_str(&format!(
            r#"
def {name}Witness : List Nat := {witness}
def {name}Instrs : List Instr := {actual}

theorem {name}_validated :
    {call} = true := by
  decide

/-- Every input, with sufficient budget and no cancellation: a theorem about this model. -/
theorem {name}_sound (inputs : Nat → BitVec 64) :
    runOutputs inputs preloads {name}Instrs outRegs =
      PackedSchedule.referenceOutputs (graph nodes) inputs outputs :=
  accepted_stream_sound nodes regs nodeLayers layers preloads {name}Witness
    {name}Instrs outputs outRegs {name}_validated inputs
"#,
            witness = numbers(&artifact.witness),
            call = call(name, "", "", "", "")
        ));
    }
    let mut cross = first.clone();
    cross.witness.swap(1, 2);
    cross.stream.swap(1, 2);
    let mut swapped_sub = first.clone();
    let at = swapped_sub
        .stream
        .iter()
        .position(|ins| matches!(ins, I64Instruction::Sub(..)))
        .expect("subtraction");
    if let I64Instruction::Sub(d, a, b) = swapped_sub.stream[at] {
        swapped_sub.stream[at] = I64Instruction::Sub(d, b, a);
    }
    let mut duplicate = first.clone();
    duplicate.witness[1] = duplicate.witness[0];
    duplicate.stream[1] = duplicate.stream[0];
    let mut omitted = first.clone();
    omitted.witness.pop();
    omitted.stream.pop();
    let mut early = first.clone();
    if let I64Instruction::Sub(d, _, b) = early.stream[0] {
        early.stream[0] = I64Instruction::Sub(d, layout.reg[6], b);
    } else {
        panic!("first operation must be subtraction");
    }
    let mut double_writer = first.clone();
    if let I64Instruction::Add(_, a, b) = double_writer.stream[1] {
        double_writer.stream[1] = I64Instruction::Add(layout.reg[4], a, b);
    } else {
        panic!("second operation must be addition");
    }
    let mut wrong_node = first.clone();
    wrong_node.witness.swap(0, 1);
    let mut changed_outputs = first.output_regs.clone();
    changed_outputs.swap(0, 1);
    let mut changed_preloads = preloads;
    let constant_at = changed_preloads
        .iter()
        .position(|term| term.starts_with(".setConst"))
        .expect("constant");
    changed_preloads[constant_at] = format!(".setConst {} 0x0000000000000001", layout.consts[0].0);
    for (name, artifact, preload, outputs) in [
        ("cross_layer", &cross, "", String::new()),
        ("swapped_sub", &swapped_sub, "", String::new()),
        ("duplicate", &duplicate, "", String::new()),
        ("omitted", &omitted, "", String::new()),
        ("early_read", &early, "", String::new()),
        ("duplicate_destination", &double_writer, "", String::new()),
        ("wrong_witness", &wrong_node, "", String::new()),
        ("changed_output", first, "", numbers(&changed_outputs)),
        ("changed_constant", first, "changedPreloads", String::new()),
    ] {
        if name == "changed_constant" {
            source.push_str(&format!(
                "\ndef changedPreloads : List Instr := {}\n",
                words(&changed_preloads)
            ));
        }
        let witness = numbers(&artifact.witness);
        let instructions = words(
            &artifact
                .stream
                .iter()
                .copied()
                .map(instruction)
                .collect::<Vec<_>>(),
        );
        let expression = call("first", &witness, &instructions, preload, &outputs);
        source.push_str(&format!("\n/-- Refused mutation of the first real artifact. -/\ntheorem {name}_refused :\n    {expression} = false := by\n  decide\n"));
    }
    let args = [Value::I64(i64::MAX), Value::I64(i64::MIN)];
    let accepted = permutation::check(checked, first).expect("the noncanonical artifact validates");
    let actual = permutation::execute(
        accepted,
        &args,
        graph.nodes.len() as u64,
        u64::from(layout.regs) * 8,
    )
    .expect("sufficient resources");
    let result = actual
        .iter()
        .map(|value| match value {
            Value::I64(bits) => format!("some (.i64 0x{:016X})", bits.cast_unsigned()),
            Value::Bool(bit) => format!("some (.boolean {bit})"),
            Value::F32(_) => panic!("F32 outside slice"),
        })
        .collect::<Vec<_>>()
        .join(", ");
    source.push_str(&format!(
        r#"
/-- Finite supporting execution evidence, not a general executor correspondence theorem. -/
theorem first_execution_0_agrees :
    runOutputs (fun slot => if slot = 0 then 0x7FFFFFFFFFFFFFFF else 0x8000000000000000)
      preloads firstInstrs outRegs = [{result}] := by
  decide

/-- The two accepted permutations genuinely change different operation pairs. -/
theorem distinct_orders : canonicalWitness ≠ firstWitness ∧
    canonicalWitness ≠ secondWitness ∧ firstWitness ≠ secondWitness := by
  decide

end NobleFoundation.PackedPermutationCorpus
"#
    ));
    source
}

fn emitted() -> (Vec<u8>, String) {
    let (checked, artifacts) = super::permutation::variants();
    let encoded = permutation::encode(&artifacts[1]).expect("bounded actual export");
    let parsed = permutation::decode(&encoded).expect("decode real export");
    assert_eq!(parsed, artifacts[1], "no normalized or substituted field");
    let triplet = [artifacts[0].clone(), parsed, artifacts[2].clone()];
    (encoded, corpus(&checked, &triplet))
}

#[test]
fn committed_noncanonical_binary_and_model_corpus_match_real_emission() {
    let (bytes, lean) = emitted();
    assert_eq!(std::fs::read(BINARY).expect("retained binary"), bytes);
    assert_eq!(
        std::fs::read_to_string(LEAN).expect("retained Lean corpus"),
        lean
    );
}

#[test]
#[ignore = "deliberately refreshes real exported artifacts; source and proof need a new receipt"]
fn write_real_artifacts() {
    let (binary, lean) = emitted();
    std::fs::write(BINARY, binary).expect("real noncanonical binary written");
    std::fs::write(LEAN, lean).expect("Lean corpus written");
}
