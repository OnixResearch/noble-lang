use super::*;
use std::fmt;

fn lean_preamble() -> String {
    String::from(
        "import NobleFoundation.LlvmLowering\n\n\
         /-!\n\
         # Real graph-to-LLVM artifacts, validated by the Lean kernel (issue #107)\n\n\
         Generated by `crates/noble-ngraph/tests/cert/llvm/corpus.rs` from the modules the emitter renders \\
         and the instruction lists the *validator's own parser* reads back out of those bytes; do \
         not edit by hand. `the_lean_corpus_is_the_real_export` fails when either changes, until \
         this file is regenerated and the foundation lane rerun.\n\n\
         For every artifact the kernel decides `validate` (`*_validated`), and `validate_sound` gives \
         the semantic theorem (`*_sound`): the executed function returns the graph reference's value \
         of the selected output for every pair of `BitVec 64` inputs. Every `*_refused` theorem is \
         the same graph with one obligation broken — the parsed instructions are the ones the Rust \
         validator refused for the same bytes — and the kernel decides that `validate` refuses them. \
         Every `*_execution_*_agrees` theorem states the value the Rust interpreter read from the \
         same parsed instructions at named inputs, after the generator checked it against the Rust \
         graph reference, and the kernel evaluates `result` to it; by `*_sound` it is also the graph \
         reference's value.\n\n\
         The exported form is the parser's, not the emitter's. The one trusted translation is that \
         reading: these statements are about the parsed instruction list, and nothing here says the \
         parser, the emitter or the Rust checker corresponds to this model.\n\
         -/\n\n\
         namespace NobleFoundation.LlvmLoweringCorpus\n\n\
         open NobleFoundation.LlvmLowering\n\
         open NobleFoundation.PackedSchedule\n\
         open NobleFoundation.FirstProjection\n",
    )
}

fn append_execution(
    text: &mut impl fmt::Write,
    held: &Artifact,
    index: usize,
    inputs: [i64; 2],
) -> fmt::Result {
    let name = lean_name(held.name);
    let observed = executed(held, inputs);
    write!(
        text,
        "\n/-- The Rust interpreter, agreeing with the graph reference here, read {bits} at \
         ({left}, {right}). -/\n\
         theorem {name}_execution_{index}_agrees :\n    \
         result (inputsOf [{left}, {right}]) {name}Instrs {name}Out = some (.i64 {bits}) :=\n  \
         by decide\n",
        bits = hex_bits(observed),
        left = hex_bits(inputs[0]),
        right = hex_bits(inputs[1]),
    )
}

fn append_fixture(text: &mut impl fmt::Write, held: &Artifact) -> fmt::Result {
    let name = lean_name(held.name);
    let nodes: Vec<String> = held
        .graph
        .nodes
        .iter()
        .map(|node| lean_node(&node.op))
        .collect();
    let instructions: Vec<String> = held
        .module
        .instructions
        .iter()
        .map(lean_instruction)
        .collect();
    let output = held.graph.outputs.first().expect("one selected output").0;
    write!(
        text,
        "\n/-! ## `{name}`: {doc} -/\n\n\
         def {name}Nodes : List Node :={nodes}\n\n\
         def {name}Graph : Graph := FirstProjection.ofList {name}Nodes {output}\n\n\
         def {name}Instrs : List NobleFoundation.LlvmLowering.Instr :={instructions}\n\n\
         def {name}Out : Operand := {out}\n\n\
         theorem {name}_validated : validate {name}Graph {name}Instrs {name}Out = true := by\n  \
         decide\n\n\
         theorem {name}_wellFormed : WellFormed {name}Graph :=\n  \
         FirstProjection.ofList_wellFormed {name}Nodes {output} (by decide) (by decide)\n\n\
         /-- The parsed body returns the graph reference's output for every input pair. -/\n\
         theorem {name}_sound (inputs : Nat → BitVec 64) :\n    \
         result inputs {name}Instrs {name}Out = value {name}Graph inputs {name}Graph.output :=\n  \
         validate_sound {name}Graph {name}_wellFormed {name}Instrs {name}Out {name}_validated \
         inputs\n",
        doc = held.doc,
        nodes = term_list(&nodes),
        instructions = term_list(&instructions),
        out = lean_operand(held.module.output),
    )?;
    for (index, inputs) in EXECUTIONS.iter().enumerate() {
        append_execution(text, held, index, *inputs)?;
    }
    Ok(())
}

fn append_control(text: &mut impl fmt::Write, record: &ControlRecord) -> fmt::Result {
    let Some(mutated) = record.mutated.as_ref() else {
        return Ok(());
    };
    let name = format!(
        "{}_{}",
        lean_name(record.artifact),
        record.class.replace('-', "_")
    );
    let graph = lean_name(record.artifact);
    let instructions: Vec<String> = mutated.instructions.iter().map(lean_instruction).collect();
    write!(
        text,
        "\n/-- Refused by the Rust validator with `{refusal}`, and refused here. -/\n\
         theorem {name}_refused :\n    \
         validate {graph}Graph{nodes} ({out}) = false := by\n  decide\n",
        refusal = record.model_refusal,
        nodes = term_list(&instructions),
        out = lean_operand(mutated.output),
    )
}

pub(super) fn lean_source(all: &[Artifact], records: &[ControlRecord]) -> String {
    let mut text = lean_preamble();
    for held in all {
        append_fixture(&mut text, held).expect("writing to String cannot fail");
    }
    text.push_str(
        "\n/-! ## Controls\n\n\
         The same graphs with one obligation broken. Each instruction list below is the parsed form \
         of bytes the Rust validator refused, so the kernel is deciding the same refusals. -/\n",
    );
    for record in records.iter().filter(|record| record.model) {
        append_control(&mut text, record).expect("writing to String cannot fail");
    }
    text.push_str("\nend NobleFoundation.LlvmLoweringCorpus\n");
    text
}

fn hex_u64(bits: u64) -> String {
    format!("0x{bits:016X}")
}

/// The actual certificate that binds the retained original and rewritten graph pair.
pub(super) fn certificate_text(all: &[Artifact]) -> String {
    let original = artifact_named(all, "foldable");
    let rewritten = artifact_named(all, "foldable-rewritten");
    let (derivation, endpoint) = noble_ngraph::cert::emit(&TestIds, &original.graph);
    assert_eq!(
        endpoint, rewritten.graph,
        "the pair is the certificate endpoint"
    );
    assert_eq!(
        noble_ngraph::cert::check(&TestIds, &original.graph, &rewritten.graph, &derivation),
        Ok(()),
        "the retained certificate validates"
    );
    let steps: Vec<String> = derivation
        .steps
        .iter()
        .map(|step| {
            format!(
                "    {{\"rule\": {}, \"node\": {}, \"operands\": [{}, {}], \
                 \"first_bits\": {}, \"second_bits\": {}, \"claimed\": {}}}",
                json_string(step.rule.name()),
                step.node.0,
                step.operands[0].0,
                step.operands[1].0,
                json_string(&hex_u64(step.first_bits)),
                json_string(&hex_u64(step.second_bits)),
                json_string(&hex_u64(step.claimed))
            )
        })
        .collect();
    format!(
        "{{\n  \"schema\": \"ngraph-certificate-pair/v1\",\n  \"revision\": {},\n  \
         \"left\": {},\n  \"right\": {},\n  \"steps\": [\n{}\n  ]\n}}\n",
        json_string(&derivation.revision),
        json_string(&noble_ngraph::ir::hex(&derivation.left)),
        json_string(&noble_ngraph::ir::hex(&derivation.right)),
        steps.join(",\n")
    )
}
