use super::emit::{hex, layer_list, nat_list, suffix_list, term_list, Artifact};

pub(crate) const GUARDED_HEADER: &str = r##"import NobleFoundation.PackedScheduleCorpus
import NobleFoundation.PackedScheduleGuard

/-!
# Guarded packed I64/Bool artifact, validated by the Lean kernel (issue #43)

Generated by `corpus_guard.rs` from the declaration and stream `Compiled::new` emits; do not edit
by hand. `the_guarded_lean_file_is_the_real_emission` fails when the emitted artifact changes.

The kernel decides the guarded validator, its well-formedness premise and suffix-table identity.
`machineObs` reads guard operands from the packed register file; `validate_machineValue_sound`
proves those values match the graph reference. `validate_sound` proves the supplied stream's
observation equals the canonical graph reference; `layeredObs_sound` proves the suffix-aware
packed-layer observation agrees as well. Each refused
mutation changes one obligation, and each concrete execution row was compared with the Rust
reference interpreter before the Lean machine was evaluated.

The export is per artifact. It is not a theorem about the scheduler, Rust executor, host or engine.
-/

namespace NobleFoundation.PackedScheduleCorpus

open NobleFoundation.PackedSchedule

"##;

fn guarded_validate_call(name: &str, instrs: &str, out_regs: &str) -> String {
    format!(
        "NobleFoundation.PackedScheduleGuard.validate {name}Graph (regOfList {name}Regs) {name}Order{instrs} {name}Outputs {out_regs}"
    )
}

pub(crate) fn artifact_text(artifact: &Artifact) -> String {
    let name = artifact.name;
    let mut text = format!(
        r##"/-! ## `{name}`: {doc} -/

def {name}Nodes : List NobleFoundation.PackedScheduleGuard.Node :={nodes}

def {name}Graph : NobleFoundation.PackedScheduleGuard.Graph :=
  {{ count := {name}Nodes.length, node := fun index => {name}Nodes.getD index (.input 0) }}

def {name}Regs : List Nat := {regs}

def {name}Order : List Nat := {order}

def {name}Layers : List (List Nat) := {layers}

def {name}FailSuffixMin : List (Option Nat) := {suffix_min}

def {name}LayerGuardOrder : List Nat := {layer_guard_order}

def {name}Instrs : List NobleFoundation.PackedScheduleGuard.Instr :={instrs}

def {name}Outputs : List Nat := {outputs}

def {name}OutRegs : List Nat := {out_regs}

theorem {name}_validated :
    {call} = true := by
  decide

theorem {name}_wellFormed : NobleFoundation.PackedScheduleGuard.WellFormed {name}Graph := by
  change NobleFoundation.PackedScheduleGuard.wellFormedBool {name}Graph = true
  decide

theorem {name}_suffix_table_matches :
    ({name}FailSuffixMin.drop 1) =
      (NobleFoundation.PackedScheduleGuard.failSuffixMin
        ({name}Layers.map (NobleFoundation.PackedScheduleGuard.graphGuardLayer {name}Graph
          (regOfList {name}Regs) (fun _ => none)))).take {name}Layers.length := by
  decide

theorem {name}_sound (inputs : Nat → BitVec 64) :
    NobleFoundation.PackedScheduleGuard.machineObs {name}Graph inputs (regOfList {name}Regs)
      {name}Order {name}Instrs {name}OutRegs =
      NobleFoundation.PackedScheduleGuard.referenceObs {name}Graph inputs {name}Outputs :=
  NobleFoundation.PackedScheduleGuard.validate_sound {name}Graph {name}_wellFormed (regOfList {name}Regs)
    {name}Order {name}Instrs {name}Outputs {name}OutRegs {name}_validated inputs

theorem {name}_layered_sound (inputs : Nat → BitVec 64) :
    NobleFoundation.PackedScheduleGuard.layeredObs {name}Graph inputs {name}Layers
      (regOfList {name}Regs) {name}Instrs {name}OutRegs =
      NobleFoundation.PackedScheduleGuard.referenceObs {name}Graph inputs {name}Outputs :=
  NobleFoundation.PackedScheduleGuard.layeredObs_sound {name}Graph {name}_wellFormed inputs {name}Layers
    {name}Outputs (regOfList {name}Regs) {name}Instrs {name}OutRegs {name}_validated
"##,
        doc = artifact.doc,
        nodes = term_list(&artifact.nodes),
        regs = nat_list(&artifact.regs),
        order = nat_list(&artifact.order),
        layers = layer_list(&artifact.layers),
        suffix_min = suffix_list(&artifact.suffix_min),
        layer_guard_order = nat_list(&artifact.layer_guard_order),
        instrs = term_list(&artifact.instrs),
        outputs = nat_list(&artifact.outputs),
        out_regs = nat_list(&artifact.out_regs),
        call = guarded_validate_call(name, &format!(" {name}Instrs"), &format!("{name}OutRegs")),
    );
    text.push_str(&mutations_text(artifact));
    text.push_str(&observations_text(artifact));
    text
}

fn mutations_text(artifact: &Artifact) -> String {
    let name = artifact.name;
    artifact
        .mutations
        .iter()
        .map(|(suffix, change, instrs, out_regs)| {
            format!(
                "\n/-- Refused: {change}. -/\ntheorem {name}_{suffix}_refused :\n    {call} = false := by\n  decide\n",
                call = guarded_validate_call(
                    name,
                    &term_list(instrs).replace('\n', "\n    "),
                    &nat_list(out_regs)
                ),
            )
        })
        .collect()
}

fn observations_text(artifact: &Artifact) -> String {
    let name = artifact.name;
    let mut text = artifact
        .guarded_executions
        .iter()
        .enumerate()
        .map(|(index, (inputs, observation))| {
            let values: Vec<String> = inputs
                .iter()
                .map(|value| hex(value.cast_unsigned()))
                .collect();
            format!(
                r##"
/-- The real packed evaluator and reference interpreter agreed on this guarded observation. -/
theorem {name}_execution_{index}_agrees :
    NobleFoundation.PackedScheduleGuard.machineObs {name}Graph (inputsOf [{values}])
      (regOfList {name}Regs) {name}Order {name}Instrs {name}OutRegs =
      {observation} := by
  decide
"##,
                values = values.join(", "),
            )
        })
        .collect::<String>();
    if let Some(inputs) = &artifact.layer_order_witness {
        let values: Vec<String> = inputs
            .iter()
            .map(|value| hex(value.cast_unsigned()))
            .collect();
        let first_layer_guard = artifact
            .layer_guard_order
            .first()
            .expect("the guarded fixture has a layer guard");
        let canonical_guard = artifact
            .layer_guard_order
            .iter()
            .min()
            .expect("the guarded fixture has a canonical guard");
        text.push_str(&format!(
            r##"
/-- Both guards fail: layer order encounters the later canonical guard first, but the suffix minimum reports the canonical first failure. -/
theorem {name}_layer_guard_witness :
    {name}LayerGuardOrder = ({name}Layers.flatten).filter (fun index => ({name}Graph.node index).isGuard) ∧
    NobleFoundation.PackedScheduleGuard.minimum {name}LayerGuardOrder = some {canonical_guard} ∧
    (NobleFoundation.PackedScheduleGuard.scheduledFailures {name}Graph (regOfList {name}Regs)
      (NobleFoundation.PackedScheduleGuard.machineRun (inputsOf [{values}]) {name}Instrs)
      {name}Layers.flatten).head? = some {first_layer_guard} ∧
    NobleFoundation.PackedScheduleGuard.layeredObs {name}Graph (inputsOf [{values}]) {name}Layers
      (regOfList {name}Regs) {name}Instrs {name}OutRegs =
      NobleFoundation.PackedScheduleGuard.Obs.failed {canonical_guard} := by
  decide
"##,
            values = values.join(", "),
        ));
    }
    text
}
