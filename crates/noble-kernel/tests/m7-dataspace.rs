//! The closed ServiceRef wire format compared against the independent
//! expectations in `verification/service-ref/cases.txt` (issue #48).
//!
//! The case file is generated by `verification/service-ref/cases.mjs` from the
//! Lean model, not from this crate, so this lane measures the Rust decoder
//! against a written-down specification. The model's depth scan is balanced like
//! the decoder's; three control cases separate it from a counting-only scan.
//! Seeded decoder faults, each the decoder with one rule changed, run through the
//! same cases, and every one must disagree with at least one expectation.
const LIMITS: noble_kernel::dataspace::Limits = noble_kernel::dataspace::Limits {
    facets: 8,
    assertions: 8,
    interests: 8,
    events: 32,
};
const PRODUCER: noble_kernel::dataspace::Rights = noble_kernel::dataspace::Rights {
    publish: true,
    observe: false,
};
const OBSERVER: noble_kernel::dataspace::Rights = noble_kernel::dataspace::Rights {
    publish: false,
    observe: true,
};

#[test]
fn published_service_replaces_ready_and_scope_retirement_retracts_descendants(
) -> Result<(), noble_kernel::dataspace::Error> {
    let mut table = noble_kernel::dataspace::Table::new(LIMITS)?;
    let producer = table.open(None, PRODUCER)?;
    let child = table.open(Some(producer), PRODUCER)?;
    let observer = table.open(None, OBSERVER)?;
    assert!(!table.observe(observer, "clock", true)?);
    assert!(!table.observe(observer, "clock", false)?);
    assert!(table.publish(producer, "clock", true)?);
    assert_eq!(
        table.events()[0].change,
        noble_kernel::dataspace::Change::Added
    );
    assert!(table.publish(producer, "clock", false)?);
    assert_eq!(
        table.events()[1].change,
        noble_kernel::dataspace::Change::Removed
    );
    assert!(table.events()[1].service.ready);
    assert_eq!(
        table.events()[2].change,
        noble_kernel::dataspace::Change::Added
    );
    assert!(!table.events()[2].service.ready);
    table.publish(child, "alarm", true)?;
    table.retire(producer)?;
    assert_eq!(table.counts(), (1, 0, 2));
    assert_eq!(
        table.events()[3].change,
        noble_kernel::dataspace::Change::Removed
    );
    assert_eq!(
        table.publish(child, "alarm", true),
        Err(noble_kernel::dataspace::Error::InvalidFacet)
    );
    assert!(!table.observe(observer, "clock", false)?);
    assert_eq!(
        table.retire(producer),
        Err(noble_kernel::dataspace::Error::InvalidFacet)
    );
    Ok(())
}

#[test]
fn full_event_queue_cannot_block_mandatory_cleanup() -> Result<(), noble_kernel::dataspace::Error> {
    let mut table = noble_kernel::dataspace::Table::new(noble_kernel::dataspace::Limits {
        events: 3,
        ..LIMITS
    })?;
    let publisher = table.open(None, PRODUCER)?;
    let subscriber = table.open(None, OBSERVER)?;
    table.observe(subscriber, "clock", true)?;
    table.publish(publisher, "clock", true)?;
    // One queued Added + one reserved future Removed: a second Added would
    // consume the removal reservation, and must leave state unchanged.
    let next = table.open(None, PRODUCER)?;
    assert_eq!(table.publish(next, "clock", false), Ok(true));
    assert_eq!(table.publish(publisher, "clock", false), Ok(true));
    assert_eq!(table.events().len(), 2);
    assert_eq!(
        table.publish(publisher, "clock", true),
        Err(noble_kernel::dataspace::Error::Capacity)
    );
    table.retire(next)?;
    table.retire(publisher)?;
    assert_eq!(table.counts(), (1, 0, 1));
    assert_eq!(table.events().len(), 2);
    Ok(())
}

#[test]
fn duplicate_assertion_owners_emit_retraction_only_after_last_owner(
) -> Result<(), noble_kernel::dataspace::Error> {
    let mut table = noble_kernel::dataspace::Table::new(LIMITS)?;
    let a = table.open(None, PRODUCER)?;
    let b = table.open(None, PRODUCER)?;
    let watcher = table.open(None, OBSERVER)?;
    table.observe(watcher, "clock", true)?;
    table.publish(a, "clock", true)?;
    table.publish(b, "clock", true)?;
    assert_eq!(table.events().len(), 1);
    table.retire(a)?;
    assert!(table.observe(watcher, "clock", true)?);
    assert_eq!(table.events().len(), 1);
    table.retire(b)?;
    assert_eq!(table.events().len(), 2);
    assert_eq!(
        table.events()[1].change,
        noble_kernel::dataspace::Change::Removed
    );
    Ok(())
}

#[test]
fn duplicate_owners_use_exact_event_capacity_and_preserve_final_removal(
) -> Result<(), noble_kernel::dataspace::Error> {
    let mut table = noble_kernel::dataspace::Table::new(noble_kernel::dataspace::Limits {
        facets: 3,
        assertions: 2,
        interests: 1,
        events: 2,
    })?;
    let first = table.open(None, PRODUCER)?;
    let second = table.open(None, PRODUCER)?;
    let watcher = table.open(None, OBSERVER)?;
    assert!(!table.observe(watcher, "clock", true)?);
    assert!(table.publish(first, "clock", true)?);
    // Both available event slots are accounted for: Added is queued and the
    // eventual last-owner Removed is reserved. A duplicate costs no new slot.
    assert!(table.publish(second, "clock", true)?);
    assert_eq!(table.events().len(), 1);
    table.retire(first)?;
    assert!(table.observe(watcher, "clock", true)?);
    assert_eq!(table.events().len(), 1);
    table.retire(second)?;
    assert_eq!(table.events().len(), 2);
    assert_eq!(
        table.events()[0].change,
        noble_kernel::dataspace::Change::Added
    );
    assert_eq!(
        table.events()[1].change,
        noble_kernel::dataspace::Change::Removed
    );
    Ok(())
}

#[test]
fn hostile_preserves_is_bounded_and_schema_checked_before_typed_value(
) -> Result<(), noble_kernel::dataspace::Error> {
    for (input, error) in [
        (
            &b"<service \"clock\" #x>"[..],
            noble_kernel::dataspace::Error::Schema,
        ),
        (
            &b"<service \"clock\" \"not-a-bool\">"[..],
            noble_kernel::dataspace::Error::Schema,
        ),
        (
            &b"<service \"clock\" #t> "[..],
            noble_kernel::dataspace::Error::Schema,
        ),
        (
            &b"<service \"cl\xffck\" #t>"[..],
            noble_kernel::dataspace::Error::Schema,
        ),
        (
            &b"<service \"clock\" #:7>"[..],
            noble_kernel::dataspace::Error::Schema,
        ),
        (
            &b"<<<<<service \"x\" #t>>>>>"[..],
            noble_kernel::dataspace::Error::DepthLimit,
        ),
    ] {
        assert_eq!(
            noble_kernel::dataspace::decode_service(input, 4),
            Err(error)
        );
    }
    assert_eq!(
        noble_kernel::dataspace::decode_service(&[b'x'; 65], 4),
        Err(noble_kernel::dataspace::Error::ByteLimit)
    );
    for ready in [true, false] {
        let wire = noble_kernel::dataspace::encode_service("clock", ready)?;
        assert_eq!(
            noble_kernel::dataspace::decode_service(wire.as_bytes(), 4)?.ready,
            ready
        );
        assert_eq!(wire.as_bytes().len(), 20);
    }
    assert_eq!(
        noble_kernel::dataspace::decide_publication(Some(true), false),
        noble_kernel::dataspace::Publication::Replaced
    );
    assert!(!noble_kernel::dataspace::permits(
        OBSERVER,
        noble_kernel::dataspace::Operation::Publish
    ));
    Ok(())
}

mod service_ref_differential {
    use std::collections::BTreeMap;
    use std::fs;
    use std::path::PathBuf;

    use noble_kernel::dataspace::{
        decode_service, encode_service, valid_name, Error, MAX_NAME_BYTES, MAX_WIRE_BYTES,
        MAX_WIRE_DEPTH,
    };

    /// `<service "` before the name.
    const PREFIX_LEN: usize = 10;
    /// `" #t>` or `" #f>` after the name.
    const SUFFIX_LEN: usize = 5;

    #[derive(Debug)]
    struct Case {
        name: String,
        bytes: Vec<u8>,
        configured_depth: u32,
        expect: Expect,
    }

    #[derive(Debug)]
    enum Expect {
        Accepted { name: String, ready: bool },
        ByteLimit,
        DepthLimit,
        Schema,
    }

    impl Expect {
        fn label(&self) -> &'static str {
            match self {
                Self::Accepted { .. } => "accepted",
                Self::ByteLimit => "byteLimit",
                Self::DepthLimit => "depthLimit",
                Self::Schema => "schema",
            }
        }
    }

    fn cases_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../verification/service-ref/cases.txt")
    }

    fn unhex(text: &str) -> Vec<u8> {
        assert_eq!(text.len() % 2, 0, "hex payload has an even length");
        (0..text.len())
            .step_by(2)
            .map(|index| {
                u8::from_str_radix(&text[index..index.saturating_add(2)], 16).expect("hex byte")
            })
            .collect()
    }

    fn load_cases() -> Vec<Case> {
        let text =
            fs::read_to_string(cases_path()).expect("the independent case file is checked in");
        text.lines()
            .filter(|line| !line.trim().is_empty())
            .map(|line| {
                let fields: Vec<&str> = line.split(' ').collect();
                assert_eq!(
                    fields.len(),
                    6,
                    "case line has six fields: name depth kind name-hex ready bytes-hex"
                );
                let expect = match fields[2] {
                    "accepted" => Expect::Accepted {
                        name: String::from_utf8(unhex(fields[3]))
                            .expect("accepted names are the bytes of an ASCII name"),
                        ready: match fields[4] {
                            "1" => true,
                            "0" => false,
                            other => panic!("unexpected readiness {other}"),
                        },
                    },
                    "byteLimit" => Expect::ByteLimit,
                    "depthLimit" => Expect::DepthLimit,
                    "schema" => Expect::Schema,
                    other => panic!("unknown expectation kind {other}"),
                };
                Case {
                    name: fields[0].to_owned(),
                    bytes: unhex(fields[5]),
                    configured_depth: fields[1].parse().expect("configured depth"),
                    expect,
                }
            })
            .collect()
    }

    fn decide(case: &Case) -> String {
        decide_bytes(&case.bytes, case.configured_depth)
    }

    fn decide_bytes(bytes: &[u8], configured_depth: u32) -> String {
        match decode_service(bytes, configured_depth) {
            Ok(value) => format!("accepted {} {}", value.name, value.ready),
            Err(Error::ByteLimit) => "byteLimit".to_owned(),
            Err(Error::DepthLimit) => "depthLimit".to_owned(),
            Err(_) => "schema".to_owned(),
        }
    }

    fn expected_label(case: &Case) -> String {
        match &case.expect {
            Expect::Accepted { name, ready } => format!("accepted {name} {ready}"),
            other => other.label().to_owned(),
        }
    }

    #[test]
    fn service_ref_differential_matches_the_codec() {
        let cases = load_cases();
        let mut mismatches = Vec::new();
        let mut coverage: BTreeMap<&str, usize> = BTreeMap::new();
        let mut controls = 0;
        for case in &cases {
            let observed = decide(case);
            let expected = expected_label(case);
            *coverage.entry(case.expect.label()).or_default() += 1;
            if case.name.starts_with("control-") {
                // The control cases separate the model's balanced depth scan from a
                // counting-only one, so passing them means the comparison is sensitive
                // to that rule rather than merely agreeing.
                controls += 1;
            }
            if observed != expected {
                mismatches.push(format!(
                    "{}: expected {expected}, observed {observed} (bytes {:02x?}, depth {})",
                    case.name, case.bytes, case.configured_depth
                ));
            }
        }
        println!(
            "service-ref-differential cases={} coverage={:?} controls={controls}",
            cases.len(),
            coverage
        );
        assert!(
            controls >= 3,
            "the case file must carry the depth-scan control cases"
        );
        assert_eq!(
            coverage.values().sum::<usize>(),
            cases.len(),
            "every case must fall in exactly one coverage class"
        );
        assert!(
            mismatches.is_empty(),
            "model-to-Rust decision mismatches:\n{}",
            mismatches.join("\n")
        );
    }

    #[test]
    fn service_ref_round_trip_through_the_rust_encoder_holds() {
        // The encoder side of the same schema: a ready and a not-ready value encode
        // to the canonical bytes and decode back, and the length is the documented
        // `10 + name + 5`.
        for (name, ready, length) in [("clock", true, 20_usize), ("a", false, 16)] {
            let packet = encode_service(name, ready).expect("an admitted name encodes");
            assert_eq!(packet.as_bytes().len(), length);
            let decoded = decode_service(packet.as_bytes(), 4).expect("canonical bytes decode");
            assert_eq!(decoded.name, name);
            assert_eq!(decoded.ready, ready);
        }
        assert!(encode_service("", true).is_err());
        assert!(encode_service(&"a".repeat(33), true).is_err());
    }

    /// An empty-name record: the prefix and the suffix only.
    const EMPTY_RECORD_LEN: usize = PREFIX_LEN.saturating_add(SUFFIX_LEN);
    /// A record whose name is one byte past the name bound.
    const OVERLONG_RECORD_LEN: usize = EMPTY_RECORD_LEN
        .saturating_add(MAX_NAME_BYTES)
        .saturating_add(1);
    /// Where that extra name byte sits.
    const OVERLONG_NAME_BYTE: usize = PREFIX_LEN.saturating_add(MAX_NAME_BYTES);
    /// One byte past the wire budget.
    const OVER_BUDGET_LEN: usize = MAX_WIRE_BYTES.saturating_add(1);

    /// One seeded decoder fault: given an input, its configured depth and the decoder's own
    /// decision, the decision of the decoder with exactly one rule changed.
    type Mutant = fn(&[u8], u32, String) -> String;

    /// The seeded decoder faults. Each is simulated from the decoder's own decision plus its one
    /// changed rule, so it differs from the codec only on inputs where that rule decides
    /// differently.
    const MUTANTS: [(&str, Mutant); 9] = [
        ("CountingOnlyDepthScan", counting_only_depth_scan),
        ("DepthLimitTooStrict", depth_limit_too_strict),
        ("DepthLimitTooLenient", depth_limit_too_lenient),
        ("ByteLimitOffByOne", byte_limit_off_by_one),
        ("TrailingBytesIgnored", trailing_bytes_ignored),
        ("ForeignTagReadsNotReady", foreign_tag_reads_not_ready),
        ("ReadinessIgnored", readiness_ignored),
        ("EmptyNameAccepted", empty_name_accepted),
        ("NameLengthOffByOne", name_length_off_by_one),
    ];

    /// The deepest point of the decoder's scan: openers count up, closers saturate down.
    fn balanced_depth(bytes: &[u8]) -> u32 {
        let mut depth = 0u32;
        let mut deepest = 0u32;
        for &byte in bytes {
            if byte == b'<' {
                depth = depth.saturating_add(1);
                deepest = deepest.max(depth);
            } else if byte == b'>' {
                depth = depth.saturating_sub(1);
            }
        }
        deepest
    }

    fn openers(bytes: &[u8]) -> u32 {
        u32::try_from(bytes.iter().filter(|&&byte| byte == b'<').count())
            .expect("a case holds far fewer than u32::MAX bytes")
    }

    /// The byte budget and the configured depth both pass, so the decoder reaches its depth scan.
    fn reaches_scan(bytes: &[u8], configured_depth: u32) -> bool {
        bytes.len() <= MAX_WIRE_BYTES && configured_depth != 0 && configured_depth <= MAX_WIRE_DEPTH
    }

    /// The decoder's decision on `bytes`, kept only if it admits a record.
    fn admitted(bytes: &[u8], configured_depth: u32) -> Option<String> {
        Some(decide_bytes(bytes, configured_depth)).filter(|label| label.starts_with("accepted "))
    }

    /// Counts every opener instead of scanning with a saturating decrement. Counting refuses a
    /// superset of what the balanced scan refuses, so outside that superset the codec's decision
    /// stands.
    fn counting_only_depth_scan(bytes: &[u8], depth: u32, real: String) -> String {
        if reaches_scan(bytes, depth) && openers(bytes) > depth {
            "depthLimit".to_owned()
        } else {
            real
        }
    }

    /// Refuses at the configured depth (`>=` instead of `>`).
    fn depth_limit_too_strict(bytes: &[u8], depth: u32, real: String) -> String {
        if reaches_scan(bytes, depth) && balanced_depth(bytes) == depth {
            "depthLimit".to_owned()
        } else {
            real
        }
    }

    /// Admits one level past the configured depth. An admitted record holds exactly one opener
    /// (the name alphabet has no bracket), so an input that passes the scan only one level deeper
    /// ends in the schema checks.
    fn depth_limit_too_lenient(bytes: &[u8], depth: u32, real: String) -> String {
        if reaches_scan(bytes, depth) && balanced_depth(bytes) == depth.saturating_add(1) {
            "schema".to_owned()
        } else {
            real
        }
    }

    /// Admits one byte past the wire budget. No admitted record is that long (the longest is 47
    /// bytes), so such an input ends in the depth checks or in schema.
    fn byte_limit_off_by_one(bytes: &[u8], depth: u32, real: String) -> String {
        if bytes.len() != OVER_BUDGET_LEN {
            return real;
        }
        let is_configured = depth != 0 && depth <= MAX_WIRE_DEPTH;
        if is_configured && balanced_depth(bytes) <= depth {
            "schema".to_owned()
        } else {
            "depthLimit".to_owned()
        }
    }

    /// Decodes one record from the front and ignores the bytes after it. A record prefix passes
    /// the same budget and scan as the whole input, so the front parser admits exactly a prefix
    /// the decoder admits on its own.
    fn trailing_bytes_ignored(bytes: &[u8], depth: u32, real: String) -> String {
        if real != "schema" {
            return real;
        }
        (EMPTY_RECORD_LEN..bytes.len())
            .find_map(|end| admitted(&bytes[..end], depth))
            .unwrap_or(real)
    }

    /// Reads any tag byte other than `t` as not ready instead of refusing it.
    fn foreign_tag_reads_not_ready(bytes: &[u8], depth: u32, real: String) -> String {
        if real != "schema" || bytes.len() < SUFFIX_LEN {
            return real;
        }
        let mut retagged = bytes.to_vec();
        let tag = retagged.len().saturating_sub(2);
        if retagged[tag] != b't' {
            retagged[tag] = b'f';
        }
        admitted(&retagged, depth).unwrap_or(real)
    }

    /// Reports every admitted record as ready.
    fn readiness_ignored(bytes: &[u8], depth: u32, real: String) -> String {
        match decode_service(bytes, depth) {
            Ok(value) => format!("accepted {} true", value.name),
            Err(_) => real,
        }
    }

    /// Drops the empty-name check. A one-byte name spliced into an empty-name input is admitted
    /// exactly when every other part of the record is.
    fn empty_name_accepted(bytes: &[u8], depth: u32, real: String) -> String {
        if real != "schema" || bytes.len() != EMPTY_RECORD_LEN {
            return real;
        }
        let mut named = bytes[..PREFIX_LEN].to_vec();
        named.push(b'a');
        named.extend_from_slice(&bytes[PREFIX_LEN..]);
        admitted(&named, depth).map_or(real, |label| label.replacen(" a ", "  ", 1))
    }

    /// Admits a name one byte past the name bound. Removing that byte leaves a record the decoder
    /// admits exactly when the first 32 name bytes and every other part are admitted; the removed
    /// byte must also be in the name alphabet.
    fn name_length_off_by_one(bytes: &[u8], depth: u32, real: String) -> String {
        if real != "schema" || bytes.len() != OVERLONG_RECORD_LEN {
            return real;
        }
        let mut shortened = bytes.to_vec();
        let removed = shortened.remove(OVERLONG_NAME_BYTE);
        let is_in_alphabet = std::str::from_utf8(&[removed]).is_ok_and(valid_name);
        match decode_service(&shortened, depth) {
            Ok(value) if is_in_alphabet => format!(
                "accepted {}{} {}",
                value.name,
                char::from(removed),
                value.ready
            ),
            Ok(_) | Err(_) => real,
        }
    }

    #[test]
    fn service_ref_corpus_detects_each_declared_decoder_mutation() -> Result<(), String> {
        let cases = load_cases();
        // The simulated faults lean on `balanced_depth` matching the decoder's own scan; check
        // that on every case that reaches the scan before trusting any mutant built from it.
        for case in &cases {
            if reaches_scan(&case.bytes, case.configured_depth) {
                let is_refused = decide(case) == "depthLimit";
                let is_deeper = balanced_depth(&case.bytes) > case.configured_depth;
                if is_refused != is_deeper {
                    return Err(format!(
                        "{}: decoder depth refusal {is_refused}, scan helper {is_deeper}",
                        case.name
                    ));
                }
            }
        }
        let unmutated = cases
            .iter()
            .filter(|case| decide(case) != expected_label(case))
            .count();
        if unmutated != 0 {
            return Err(format!(
                "the unmutated decoder disagrees with {unmutated} retained expectations"
            ));
        }
        let mut report = vec![format!("None={unmutated}")];
        for (name, mutant) in MUTANTS {
            let mismatches = cases
                .iter()
                .filter(|case| {
                    mutant(&case.bytes, case.configured_depth, decide(case)) != expected_label(case)
                })
                .count();
            if mismatches == 0 {
                return Err(format!("mutation {name} is not caught by any expectation"));
            }
            report.push(format!("{name}={mismatches}"));
        }
        println!(
            "service-ref-mutations cases={} caught=[{}]",
            cases.len(),
            report.join(" ")
        );
        Ok(())
    }
}
