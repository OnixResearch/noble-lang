//! Ownership accounting corpus lane (issue #59).
//!
//! The expectations in `verification/ownership/cases.txt` are generated by
//! `verification/ownership/cases.mjs` from the Lean model in
//! `proofs/foundation/NobleFoundation/Ownership.lean` and `OwnershipTrace.lean`,
//! never from this crate. The same generator emits
//! `proofs/foundation/NobleFoundation/OwnershipCorpus.lean`, where the kernel
//! decides `run` and the per-word `runTrace` for every row, so a row whose
//! expectation does not follow from the model fails the foundation build.
//!
//! Three things are measured here, and none of them is a source-refinement
//! claim:
//!
//! 1. Every case with a production analogue is driven through the actual
//!    acceptance machine (`noble_kernel::acceptance::check` via `support::seen`)
//!    **one word prefix at a time**: after `k` words the machine's derived stack
//!    must equal the model's `k`-th trace entry, so an intermediate divergence is
//!    reported as the first diverging word instead of cancelling out by the end. A
//!    rejected case must refuse at the word the model refuses.
//! 2. The committed corpus agrees with the emission: each corpus row is compared
//!    with the docstring of the kernel-checked row that decides it.
//! 3. A test-local shadow checker mirroring the Lean definitions must agree with
//!    every corpus expectation (result *and* trace), and each declared mutation of
//!    it must be caught by at least one retained expectation.
//!
//! Cases with no production analogue (wrapped payloads, the production quotation
//! constructor, the two-arm accounting rule, the ordinary error return and the
//! operand-arity refusals) are counted and named as model-only with a stated
//! reason; they are never reported as executable production controls. When a
//! comparison does fail, the lane writes the shortest failing program and operand
//! list to `verification/ownership/minimised.txt` as a reproducer.

use std::fs;
use std::path::{Path, PathBuf};

use crate::support;

/// The same word fragment the Lean model names.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Word {
    Dup,
    Drop,
    Swap,
    Quote,
}

/// One ordered-stack payload, mirroring `NobleFoundation.Ownership.Payload`.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Payload {
    Data { tag: u32 },
    Resource { tag: u32 },
    Wrapped { inner: Box<Payload> },
}

impl Payload {
    fn contains_resource(&self) -> bool {
        match self {
            Payload::Wrapped { inner } => inner.contains_resource(),
            Payload::Data { .. } => false,
            Payload::Resource { .. } => true,
        }
    }

    fn duplicable(&self) -> bool {
        !self.contains_resource()
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Program {
    Words(Vec<Word>),
    Branch {
        then_arm: Box<Program>,
        else_arm: Box<Program>,
    },
    Fail,
}

/// The production-analogue classification of one corpus case.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Decision {
    Accepted,
    Rejected,
    ModelOnly,
}

/// Why a model-only case has no production analogue. Every token is declared in
/// `REASONS` of the generator and restated in the corpus header.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Reason {
    BranchAccounting,
    ErrorReturn,
    QuotationProgramValue,
    WrappedPayload,
    OperandArity,
}

impl Reason {
    fn parse(text: &str) -> Option<Reason> {
        match text {
            "branch-accounting" => Some(Reason::BranchAccounting),
            "error-return" => Some(Reason::ErrorReturn),
            "quotation-program-value" => Some(Reason::QuotationProgramValue),
            "wrapped-payload" => Some(Reason::WrappedPayload),
            "operand-arity" => Some(Reason::OperandArity),
            _ => None,
        }
    }

    const fn token(self) -> &'static str {
        match self {
            Reason::BranchAccounting => "branch-accounting",
            Reason::ErrorReturn => "error-return",
            Reason::QuotationProgramValue => "quotation-program-value",
            Reason::WrappedPayload => "wrapped-payload",
            Reason::OperandArity => "operand-arity",
        }
    }
}

#[derive(Clone, Debug)]
struct Case {
    name: String,
    /// The corpus row exactly as committed, for the emission comparison.
    row: String,
    program: Program,
    operands: Vec<Payload>,
    expected: Option<Vec<Payload>>,
    /// The per-word trace, `None` for a program that is not a word sequence.
    trace: Option<Vec<Vec<Payload>>>,
    decision: Decision,
    reason: Option<Reason>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mutation {
    None,
    ResourceOperandDuplicated,
    ResourceOperandReleased,
    SwapDropsOperand,
    QuoteConsumesOperand,
    BranchPicksThenArm,
    FailAllowsOutstandingOperand,
}

