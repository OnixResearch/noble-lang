fn parse_payload(text: &str) -> Payload {
    if let Some(tag) = text.strip_prefix("d:") {
        return Payload::Data {
            tag: tag.parse().unwrap_or(0),
        };
    }
    if text == "r" {
        return Payload::Resource { tag: 0 };
    }
    if let Some(tag) = text.strip_prefix("r:") {
        return Payload::Resource {
            tag: tag.parse().unwrap_or(0),
        };
    }
    if let Some(inner) = text.strip_prefix("w:") {
        return Payload::Wrapped {
            inner: Box::new(parse_payload(inner)),
        };
    }
    panic!("unknown payload kind {text}");
}

fn parse_words(text: &str) -> Option<Vec<Word>> {
    let mut words = Vec::new();
    for item in text.split('+') {
        words.push(match item {
            "dup" => Word::Dup,
            "drop" => Word::Drop,
            "swap" => Word::Swap,
            "quote" => Word::Quote,
            _ => return None,
        });
    }
    Some(words)
}

fn parse_program(text: &str) -> Program {
    if let Some(inner) = text
        .strip_prefix("branch(")
        .and_then(|rest| rest.strip_suffix(')'))
    {
        let mut parts = inner.splitn(2, '|');
        let then_text = parts.next().unwrap_or_default();
        let else_text = parts.next().unwrap_or_default();
        return Program::Branch {
            then_arm: Box::new(parse_program(then_text)),
            else_arm: Box::new(parse_program(else_text)),
        };
    }
    if text == "fail" {
        return Program::Fail;
    }
    match parse_words(text) {
        Some(words) => Program::Words(words),
        None => panic!("unknown program {text}"),
    }
}

fn parse_operands(text: &str) -> Vec<Payload> {
    if text.is_empty() || text == "empty" {
        return Vec::new();
    }
    text.split(',').map(parse_payload).collect()
}

fn parse_trace(text: &str) -> Option<Vec<Vec<Payload>>> {
    if text == "-" {
        return None;
    }
    Some(text.split(';').map(parse_operands).collect())
}

fn parse_decision(text: &str) -> Decision {
    match text {
        "accepted" => Decision::Accepted,
        "rejected" => Decision::Rejected,
        "model-only" => Decision::ModelOnly,
        other => panic!("unknown decision {other}"),
    }
}

fn load_cases() -> Vec<Case> {
    let text = fs::read_to_string(corpus_path()).expect("the independent corpus is checked in");
    let mut cases = Vec::new();
    for line in text.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let mut name = String::new();
        let mut program = Program::Fail;
        let mut operands = Vec::new();
        let mut expected: Option<Vec<Payload>> = None;
        let mut trace = None;
        let mut decision = Decision::Rejected;
        let mut reason = None;
        for field in line.split_whitespace() {
            if let Some(value) = field.strip_prefix("ops=") {
                program = parse_program(value);
            } else if let Some(value) = field.strip_prefix("in=") {
                operands = parse_operands(value);
            } else if let Some(value) = field.strip_prefix("out=") {
                expected = if value == "-" {
                    None
                } else {
                    Some(parse_operands(value))
                };
            } else if let Some(value) = field.strip_prefix("trace=") {
                trace = parse_trace(value);
            } else if let Some(value) = field.strip_prefix("decision=") {
                decision = parse_decision(value);
            } else if let Some(value) = field.strip_prefix("reason=") {
                reason = if value == "-" {
                    None
                } else {
                    Some(Reason::parse(value).unwrap_or_else(|| panic!("unknown reason {value}")))
                };
            } else {
                name = field.to_string();
            }
        }
        cases.push(Case {
            name,
            row: line.to_string(),
            program,
            operands,
            expected,
            trace,
            decision,
            reason,
        });
    }
    cases
}

fn render_payload(payload: &Payload) -> String {
    match payload {
        Payload::Wrapped { inner } => format!("w:{}", render_payload(inner)),
        Payload::Data { tag } => format!("d:{tag}"),
        Payload::Resource { tag } => format!("r:{tag}"),
    }
}

fn render_stack(stack: &[Payload]) -> String {
    if stack.is_empty() {
        return "empty".to_string();
    }
    stack
        .iter()
        .map(render_payload)
        .collect::<Vec<String>>()
        .join(",")
}

fn render_trace(trace: Option<&Vec<Vec<Payload>>>) -> String {
    match trace {
        None => "-".to_string(),
        Some(entries) => entries
            .iter()
            .map(|stack| render_stack(stack))
            .collect::<Vec<String>>()
            .join(";"),
    }
}

fn render_program(program: &Program) -> String {
    match program {
        Program::Words(words) => render_words(words),
        Program::Branch { then_arm, else_arm } => {
            format!(
                "branch({}|{})",
                render_program(then_arm),
                render_program(else_arm)
            )
        }
        Program::Fail => "fail".to_string(),
    }
}

fn render_words(words: &[Word]) -> String {
    let items: Vec<&str> = words
        .iter()
        .map(|word| match word {
            Word::Dup => "dup",
            Word::Drop => "drop",
            Word::Swap => "swap",
            Word::Quote => "quote",
        })
        .collect();
    items.join("+")
}

/// The corpus row this case parses back into. It must reproduce the committed
/// line exactly, so a parser drift cannot silently pass.
fn render_row(case: &Case) -> String {
    [
        case.name.clone(),
        format!("ops={}", render_program(&case.program)),
        format!("in={}", render_stack(&case.operands)),
        format!(
            "out={}",
            match &case.expected {
                None => "-".to_string(),
                Some(stack) => render_stack(stack),
            }
        ),
        format!("trace={}", render_trace(case.trace.as_ref())),
        format!(
            "decision={}",
            match case.decision {
                Decision::Accepted => "accepted",
                Decision::Rejected => "rejected",
                Decision::ModelOnly => "model-only",
            }
        ),
        format!(
            "reason={}",
            match case.reason {
                None => "-".to_string(),
                Some(reason) => reason.token().to_string(),
            }
        ),
    ]
    .join(" ")
}

/// `NobleFoundation.Ownership.step`, with one declared variation per mutation.
fn shadow_step(mutation: Mutation, word: Word, operands: &[Payload]) -> Option<Vec<Payload>> {
    let mut stack = operands.to_vec();
    let first = stack.first().cloned();
    let second = stack.get(1).cloned();
    match word {
        Word::Dup => {
            let operand = first?;
            let duplicate = mutation == Mutation::ResourceOperandDuplicated || operand.duplicable();
            if !duplicate {
                return None;
            }
            let mut out = stack.clone();
            out.insert(1, operand);
            Some(out)
        }
        Word::Drop => {
            let operand = first?;
            let released = mutation == Mutation::ResourceOperandReleased || operand.duplicable();
            if !released {
                return None;
            }
            stack.remove(0);
            Some(stack)
        }
        Word::Swap => {
            let _ = (first?, second?);
            stack.swap(0, 1);
            if mutation == Mutation::SwapDropsOperand {
                stack.remove(1);
            }
            Some(stack)
        }
        Word::Quote => {
            let operand = first?;
            if !operand.duplicable() {
                return None;
            }
            if mutation == Mutation::QuoteConsumesOperand {
                stack.remove(0);
            }
            Some(stack)
        }
    }
}

/// `NobleFoundation.Ownership.runWords`, with the same declared variations.
fn shadow_run_words(
    mutation: Mutation,
    words: &[Word],
    operands: &[Payload],
) -> Option<Vec<Payload>> {
    let mut current = operands.to_vec();
    for word in words {
        current = shadow_step(mutation, *word, current.as_slice())?;
    }
    Some(current)
}

/// `NobleFoundation.Ownership.run`, with the same declared variations.
fn shadow_run(mutation: Mutation, program: &Program, operands: &[Payload]) -> Option<Vec<Payload>> {
    match program {
        Program::Words(words) => shadow_run_words(mutation, words, operands),
        Program::Branch { then_arm, else_arm } => {
            let then_out = shadow_run(mutation, then_arm, operands)?;
            let else_out = shadow_run(mutation, else_arm, operands)?;
            if mutation != Mutation::BranchPicksThenArm && then_out != else_out {
                return None;
            }
            Some(then_out)
        }
        Program::Fail => {
            if mutation == Mutation::FailAllowsOutstandingOperand || operands.is_empty() {
                Some(operands.to_vec())
            } else {
                None
            }
        }
    }
}

/// `NobleFoundation.Ownership.traceWords`, with the same declared variations:
/// the incoming stack first, then one entry per admitted word.
fn shadow_trace_words(
    mutation: Mutation,
    words: &[Word],
    operands: &[Payload],
) -> Vec<Vec<Payload>> {
    let mut entries = vec![operands.to_vec()];
    let mut current = operands.to_vec();
    for word in words {
        match shadow_step(mutation, *word, current.as_slice()) {
            None => return entries,
            Some(next) => {
                entries.push(next.clone());
                current = next;
            }
        }
    }
    entries
}

/// The shadow trace of a program; `None` when the program is not a word sequence.
fn shadow_trace(
    mutation: Mutation,
    program: &Program,
    operands: &[Payload],
) -> Option<Vec<Vec<Payload>>> {
    match program {
        Program::Words(words) => Some(shadow_trace_words(mutation, words, operands)),
        Program::Branch { .. } | Program::Fail => None,
    }
}

/// The production refusal class a rejected corpus case surfaced.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum ProductionCategory {
    Eligibility,
    StackJoin,
    Other,
}

/// Kernel types for payloads the acceptance machine can name as a binding.
fn kernel_type(payload: &Payload) -> Result<noble_kernel::types::Ty, String> {
    match payload {
        Payload::Data { tag } => {
            if *tag == 1 {
                Ok(support::text_ty())
            } else {
                Ok(support::i64_ty())
            }
        }
        Payload::Resource { .. } => Ok(noble_kernel::types::Ty::Resource(
            noble_kernel::contracts::FIXTURE_RESOURCE,
        )),
        Payload::Wrapped { .. } => Err("a wrapped payload has no kernel binding type".to_string()),
    }
}

fn definition(word: Word) -> noble_kernel::contracts::Definition {
    noble_kernel::contracts::Definition(match word {
        Word::Dup => 0,
        Word::Drop => 1,
        Word::Swap => 2,
        Word::Quote => 8,
    })
}

fn word_values(word: Word) -> usize {
    match word {
        Word::Swap => 2,
        Word::Dup | Word::Drop | Word::Quote => 1,
    }
}

/// Pushes one operand payload onto the derived stack.
fn push_node(
    payload: &Payload,
    maker: noble_kernel::contracts::Definition,
) -> Result<noble_kernel::untrusted::Node, String> {
    match payload {
        Payload::Data { tag } => Ok(support::lit_node(
            if *tag == 1 {
                noble_kernel::untrusted::Lit::Text
            } else {
                noble_kernel::untrusted::Lit::I64(0)
            },
            vec![],
        )),
        Payload::Resource { .. } => Ok(support::invocation(maker, vec![support::segment(vec![])])),
        Payload::Wrapped { .. } => Err("a wrapped payload has no production analogue".to_string()),
    }
}

/// The environment the production candidates are checked against: the bootstrap
/// table plus one resource-producing scheme for the corpus payloads.
fn production_environment() -> Result<
    (
        noble_kernel::contracts::Env,
        noble_kernel::contracts::Definition,
    ),
    String,
> {
    let mut env = noble_kernel::contracts::environment().map_err(|defect| format!("{defect:?}"))?;
    let maker = noble_kernel::contracts::Definition(
        env.defs
            .len()
            .try_into()
            .map_err(|_| "definition table overflow".to_string())?,
    );
    env.defs.push(noble_kernel::words::Scheme {
        var_kinds: vec![noble_kernel::words::VariableKind::Stack],
        stack_in: vec![noble_kernel::shapes::Pattern::StackVar(
            noble_kernel::words::Variable(0),
        )],
        stack_out: vec![
            noble_kernel::shapes::Pattern::StackVar(noble_kernel::words::Variable(0)),
            noble_kernel::shapes::Pattern::Resource(noble_kernel::contracts::FIXTURE_RESOURCE),
        ],
        effects: vec![],
    });
    env.kinds.push(noble_kernel::contracts::Behavior::Named);
    env.deps.push(Vec::new());
    Ok((env, maker))
}

/// One production candidate for the first `count` words of a case, with the
/// operand pushes in reverse order so the model's head is the top of the stack.
/// Each invocation binds the value types the model's trace records for the stack
/// that word actually sees, which is what makes a per-word comparison meaningful.
fn prefix_candidate(
    case: &Case,
    words: &[Word],
    trace: &[Vec<Payload>],
    count: usize,
    maker: noble_kernel::contracts::Definition,
) -> Result<noble_kernel::untrusted::Candidate, String> {
    let mut nodes = Vec::new();
    for operand in case.operands.iter().rev() {
        nodes.push(push_node(operand, maker)?);
    }
    for (index, word) in words.iter().take(count).enumerate() {
        if *word == Word::Quote {
            return Err(format!(
                "{}: the quotation constructor has no retain-in-place production analogue",
                case.name
            ));
        }
        let incoming = trace
            .get(index)
            .ok_or_else(|| format!("{}: no trace entry for word {index}", case.name))?;
        let top = incoming
            .first()
            .ok_or_else(|| format!("{}: word {index} has no operand to inspect", case.name))?;
        let mut bindings = vec![support::segment(vec![])];
        if word_values(*word) == 2 {
            // The production scheme binds the deeper operand first, so the model's
            // second operand occupies the first value slot.
            let second = incoming.get(1).ok_or_else(|| {
                format!("{}: word {index} names one operand for a pair", case.name)
            })?;
            bindings.push(support::value(kernel_type(second)?));
            bindings.push(support::value(kernel_type(top)?));
        } else {
            bindings.push(support::value(kernel_type(top)?));
        }
        nodes.push(support::invocation(definition(*word), bindings));
    }
    let body: Vec<u32> = (0..nodes.len() as u32).collect();
    Ok(support::candidate(nodes, body))
}

/// The expected production stack after `count` words: the model's stack in
/// bottom-to-top order, as the machine reports it.
fn expected_types(stack: &[Payload]) -> Result<Vec<noble_kernel::types::Ty>, String> {
    stack.iter().rev().map(kernel_type).collect()
}

/// Drives one word prefix through the acceptance machine. `expected` is the stack
/// the request asks the machine to derive: the model trace entry after the prefix
/// for an accepted prefix, or the stack the word inspects when the word itself is
/// the refused one, so a wrongly admitted word surfaces as a stack-join mismatch
/// instead of being mistaken for a refusal.
struct PrefixDriver<'a> {
    env: &'a noble_kernel::contracts::Env,
    case: &'a Case,
    words: &'a [Word],
    trace: &'a [Vec<Payload>],
    maker: noble_kernel::contracts::Definition,
}

fn drive_prefix(
    driver: &PrefixDriver<'_>,
    count: usize,
    expected: &[Payload],
) -> Result<support::Seen, String> {
    let candidate = prefix_candidate(driver.case, driver.words, driver.trace, count, driver.maker)?;
    let request = support::request(vec![], expected_types(expected)?, &[]);
    support::seen(driver.env, &request, &candidate)
}

/// Drives every prefix of a word sequence and reports the first divergence
/// against the model trace. `Ok` means every accepted prefix matched and, for a
/// refused case, the word the model refuses is refused too.
fn drive_trace(
    env: &noble_kernel::contracts::Env,
    case: &Case,
    words: &[Word],
    trace: &[Vec<Payload>],
    maker: noble_kernel::contracts::Definition,
) -> Result<(usize, Option<ProductionCategory>), String> {
    if trace.is_empty() {
        return Err(format!("{}: the trace has no entry", case.name));
    }
    let driver = PrefixDriver {
        env,
        case,
        words,
        trace,
        maker,
    };
    let accepted_words = trace.len() - 1;
    for count in 1..=accepted_words {
        let entry = trace.get(count).ok_or_else(|| {
            format!(
                "{}: no trace entry after the first {count} words",
                case.name
            )
        })?;
        match drive_prefix(&driver, count, entry)? {
            support::Seen::Accepted(checked) => {
                let expected = expected_types(&trace[count])?;
                if checked.interface.stack_out != expected {
                    return Err(format!(
                        "{}: first divergence at word {count} ({}): production derived {:?} instead of the model's {:?}",
                        case.name,
                        render_words(&words[..count]),
                        checked.interface.stack_out,
                        expected
                    ));
                }
            }
            support::Seen::Bad(diagnostic) => {
                return Err(format!(
                    "{}: prefix {} was refused ({:?}) at word {count}",
                    case.name,
                    render_words(&words[..count]),
                    diagnostic.constraint
                ));
            }
            support::Seen::Exhausted(limit) => {
                return Err(format!("{}: prefix {count} exhausted {limit:?}", case.name));
            }
        }
    }
    if accepted_words == words.len() {
        return Ok((accepted_words, None));
    }
    let count = accepted_words + 1;
    let inspected = trace
        .get(count - 1)
        .ok_or_else(|| format!("{}: no trace entry for the refused word {count}", case.name))?;
    match drive_prefix(&driver, count, inspected)? {
        support::Seen::Accepted(_) => Err(format!(
            "{}: the model refuses {} but production accepts it",
            case.name,
            render_words(&words[..count])
        )),
        support::Seen::Bad(diagnostic) => {
            let category = match diagnostic.constraint {
                noble_kernel::untrusted::Constraint::Eligibility(_) => {
                    ProductionCategory::Eligibility
                }
                noble_kernel::untrusted::Constraint::StackJoin => ProductionCategory::StackJoin,
                _ => ProductionCategory::Other,
            };
            Ok((count, Some(category)))
        }
        support::Seen::Exhausted(limit) => {
            Err(format!("{}: refused word exhausted {limit:?}", case.name))
        }
    }
}

/// Parses the docstring rows of the kernel-checked emission.
fn lean_corpus_rows() -> Result<Vec<(String, String)>, String> {
    let path = lean_corpus_path();
    let text = fs::read_to_string(&path).map_err(|error| format!("{}: {error}", path.display()))?;
    let mut rows = Vec::new();
    for line in text.lines() {
        let line = line.trim_start();
        let Some(rest) = line.strip_prefix("/-- `") else {
            continue;
        };
        let Some((name, rest)) = rest.split_once("` ") else {
            continue;
        };
        let Some(row) = rest.strip_suffix(" -/") else {
            continue;
        };
        rows.push((name.to_string(), row.to_string()));
    }
    Ok(rows)
}

/// The theorem names the emission declares, so a missing row is noticed.
fn lean_corpus_theorems() -> Result<Vec<String>, String> {
    let path = lean_corpus_path();
    let text = fs::read_to_string(&path).map_err(|error| format!("{}: {error}", path.display()))?;
    let mut names = Vec::new();
    for line in text.lines() {
        let Some(rest) = line.trim_start().strip_prefix("theorem case_") else {
            continue;
        };
        let name = rest.split_whitespace().next().unwrap_or_default();
        names.push(format!("case_{name}"));
    }
    Ok(names)
}

fn case_theorem(name: &str) -> String {
    format!("case_{}", name.replace('-', "_"))
}

/// A divergence probe over a bare word program: `Some` carries the failure
/// message and `None` means production agreed with the model trace.
type MismatchProbe<'a> = dyn Fn(&[Word], &[Payload]) -> Option<String> + 'a;

/// A shrinking candidate from an accepted production case must still be
/// accepted by the model; otherwise an unrelated arity refusal can masquerade
/// as the original production divergence.
fn candidate_preserves_model_acceptance(
    source_case: &Case,
    words: &[Word],
    trace: &[Vec<Payload>],
) -> bool {
    source_case.decision != Decision::Accepted || trace.len() == words.len() + 1
}

/// A deterministic reproducer: the shortest failing word prefix with the fewest
/// trailing operands that still fails the probe. Leading operands are not
/// removed, because they are the head the word inspects.
fn minimise_fixture(
    name: &str,
    words: &[Word],
    operands: &[Payload],
    probe: &MismatchProbe<'_>,
) -> String {
    let mut shortest = words.to_vec();
    for count in 1..=words.len() {
        if probe(&words[..count], operands).is_some() {
            shortest = words[..count].to_vec();
            break;
        }
    }
    let mut minimal = operands.to_vec();
    while minimal.len() > 1 {
        let mut shorter = minimal.clone();
        shorter.pop();
        if probe(shortest.as_slice(), shorter.as_slice()).is_some() {
            minimal = shorter;
        } else {
            break;
        }
    }
    let divergence = probe(shortest.as_slice(), minimal.as_slice())
        .unwrap_or_else(|| "no divergence".to_string());
    format!(
        "minimised-{name} ops={} in={} divergence={divergence}",
        render_words(&shortest),
        render_stack(&minimal)
    )
}

fn write_minimised(directory: &Path, row: &str) -> Result<PathBuf, String> {
    let path = directory.join("minimised.txt");
    let header = "# Shortest failing ownership word prefix and trimmed input operands (#59).\n";
    let note = "# Regenerate after a fix by adding the row to cases.mjs and re-running the lane.\n";
    fs::write(&path, format!("{header}{note}{row}\n"))
        .map_err(|error| format!("{}: {error}", path.display()))?;
    Ok(path)
}

/// Drives a bare (words, operands) pair against the model's own trace computed by
/// the shadow checker, and reports the first divergence. This is the probe the
/// reproducer minimises: it needs no corpus row, so it can shrink one.
fn production_divergence(
    env: &noble_kernel::contracts::Env,
    source_case: &Case,
    words: &[Word],
    operands: &[Payload],
    maker: noble_kernel::contracts::Definition,
) -> Option<String> {
    let trace = shadow_trace_words(Mutation::None, words, operands);
    if !candidate_preserves_model_acceptance(source_case, words, &trace) {
        return None;
    }
    let case = Case {
        name: source_case.name.clone(),
        row: String::new(),
        program: Program::Words(words.to_vec()),
        operands: operands.to_vec(),
        expected: trace.last().cloned(),
        trace: Some(trace.clone()),
        decision: source_case.decision,
        reason: source_case.reason,
    };
    let (_, observed_class) = match drive_trace(env, &case, words, &trace, maker) {
        Ok(result) => result,
        Err(message) => return Some(message),
    };
    if trace.len() == words.len() + 1 {
        return observed_class.map(|class| {
            format!(
                "{}: production refused a model-accepted prefix as {class:?}",
                source_case.name
            )
        });
    }
    let expected_class = EXPECTED_REJECTIONS
        .iter()
        .find(|entry| entry.0 == source_case.name)
        .map(|entry| entry.1);
    if observed_class != expected_class {
        return Some(format!(
            "{}: refusal class {observed_class:?}, expected {expected_class:?}",
            source_case.name
        ));
    }
    None
}

/// On a divergence, minimise the failing case into a reproducer row and keep it
/// under `verification/ownership/`.
fn failure_with_reproducer(
    env: &noble_kernel::contracts::Env,
    case: &Case,
    words: &[Word],
    message: String,
    maker: noble_kernel::contracts::Definition,
) -> String {
    let probe = |words: &[Word], operands: &[Payload]| {
        production_divergence(env, case, words, operands, maker)
    };
    let fixture = minimise_fixture(&case.name, words, case.operands.as_slice(), &probe);
    match write_minimised(&corpus_directory(), &fixture) {
        Ok(path) => format!("{message}\nreproducer: {}: {fixture}", path.display()),
        Err(error) => format!("{message}\n{error}"),
    }
}

struct CoverageCounts {
    accepted: usize,
    rejected: usize,
    model_only: usize,
    prefixes: usize,
}

fn coverage_regressed(counts: CoverageCounts) -> bool {
    if counts.accepted < 25 {
        return true;
    }
    if counts.rejected < 14 {
        return true;
    }
    if counts.model_only < 65 {
        return true;
    }
    counts.prefixes < 60
}

#[test]
fn ownership_corpus_matches_the_acceptance_machine() -> Result<(), String> {
    let cases = load_cases();
    let (env, maker) = production_environment()?;
    let mut accepted = 0;
    let mut rejected = 0;
    let mut model_only = 0;
    let mut prefixes = 0;
    let mut categories = [0_usize; 3];
    let mut reasons: Vec<(Reason, usize)> = Vec::new();
    for case in &cases {
        if render_row(case) != case.row {
            return Err(format!(
                "{}: parses back as {:?} instead of the committed row {:?}",
                case.name,
                render_row(case),
                case.row
            ));
        }
        match case.decision {
            Decision::Accepted => accepted += 1,
            Decision::Rejected => rejected += 1,
            Decision::ModelOnly => {
                model_only += 1;
                let Some(reason) = case.reason else {
                    return Err(format!("{} is model-only without a reason", case.name));
                };
                match reasons.iter_mut().find(|(token, _)| *token == reason) {
                    Some((_, count)) => *count += 1,
                    None => reasons.push((reason, 1)),
                }
            }
        }
        if case.decision != Decision::ModelOnly && case.reason.is_some() {
            return Err(format!(
                "{} has a production analogue but carries a model-only reason",
                case.name
            ));
        }
        let Program::Words(words) = &case.program else {
            if case.decision != Decision::ModelOnly {
                return Err(format!(
                    "{} is not a word sequence but is driven",
                    case.name
                ));
            }
            if case.trace.is_some() {
                return Err(format!(
                    "{} is not a word sequence but carries a trace",
                    case.name
                ));
            }
            continue;
        };
        let Some(trace) = case.trace.as_ref() else {
            return Err(format!("{} has a word program but no trace", case.name));
        };
        if let Some(expected) = case.expected.as_ref() {
            if trace.last() != Some(expected) {
                return Err(format!(
                    "{}: out= disagrees with the trace's last entry",
                    case.name
                ));
            }
        }
        match case.decision {
            Decision::ModelOnly => continue,
            Decision::Accepted => {
                if trace.len() != words.len() + 1 {
                    return Err(format!(
                        "{}: accepted with {} trace entries for {} words",
                        case.name,
                        trace.len(),
                        words.len()
                    ));
                }
            }
            Decision::Rejected => {
                if trace.len() > words.len() {
                    return Err(format!(
                        "{}: refused with {} trace entries for {} words",
                        case.name,
                        trace.len(),
                        words.len()
                    ));
                }
            }
        }
        let (driven, category) = match drive_trace(&env, case, words, trace, maker) {
            Ok(result) => result,
            Err(message) => {
                return Err(failure_with_reproducer(&env, case, words, message, maker));
            }
        };
        prefixes += driven;
        match category {
            Some(found) => {
                let expected = EXPECTED_REJECTIONS
                    .iter()
                    .find(|entry| entry.0 == case.name)
                    .map(|entry| entry.1)
                    .ok_or_else(|| {
                        format!(
                            "{} is rejected but declares no expected production class (found {found:?})",
                            case.name
                        )
                    })?;
                if found != expected {
                    let message = format!(
                        "{} was refused as {found:?}, expected {expected:?}",
                        case.name
                    );
                    return Err(failure_with_reproducer(&env, case, words, message, maker));
                }
                categories[match found {
                    ProductionCategory::Eligibility => 0,
                    ProductionCategory::StackJoin => 1,
                    ProductionCategory::Other => 2,
                }] += 1;
            }
            None => {
                if case.decision == Decision::Rejected {
                    return Err(format!(
                        "{} is rejected but production accepted every word",
                        case.name
                    ));
                }
            }
        }
    }
    if coverage_regressed(CoverageCounts {
        accepted,
        rejected,
        model_only,
        prefixes,
    }) {
        return Err(format!(
            "corpus coverage regressed: accepted={accepted} rejected={rejected} model-only={model_only} prefixes={prefixes}"
        ));
    }
    for (name, _) in EXPECTED_REJECTIONS {
        let is_rejected = cases
            .iter()
            .any(|case| case.decision == Decision::Rejected && case.name == name);
        if !is_rejected {
            return Err(format!(
                "expected refusal {name} is no longer a rejected corpus case"
            ));
        }
    }
    if categories[0] == 0 {
        return Err("no rejected case surfaced the eligibility constraint".to_string());
    }
    if categories.iter().sum::<usize>() != rejected {
        return Err(format!(
            "rejected cases {rejected} but classes total {}",
            categories.iter().sum::<usize>()
        ));
    }
    let emission = lean_corpus_rows()?;
    if emission.len() != cases.len() {
        return Err(format!(
            "kernel-checked emission has {} rows for {} corpus cases",
            emission.len(),
            cases.len()
        ));
    }
    let theorems = lean_corpus_theorems()?;
    for case in &cases {
        let matches: Vec<&(String, String)> = emission
            .iter()
            .filter(|(name, _)| *name == case.name)
            .collect();
        if matches.len() != 1 {
            return Err(format!(
                "{}: {} kernel-checked rows for one corpus case",
                case.name,
                matches.len()
            ));
        }
        if matches[0].1 != case.row {
            return Err(format!(
                "{}: kernel-checked row {:?} differs from the corpus row {:?}",
                case.name, matches[0].1, case.row
            ));
        }
        if !theorems
            .iter()
            .any(|name| *name == case_theorem(&case.name))
        {
            return Err(format!(
                "{}: the emission declares no theorem {}",
                case.name,
                case_theorem(&case.name)
            ));
        }
    }
    reasons.sort_by_key(|(reason, _)| reason.token());
    let reason_report: Vec<String> = reasons
        .iter()
        .map(|(reason, count)| format!("{}:{count}", reason.token()))
        .collect();
    println!(
        "ownership-differential cases={} accepted={accepted} rejected={rejected} model-only={model_only} prefixes={prefixes} categories=eligibility:{} stack-join:{} other:{} model-only-reasons={} first-divergence=none",
        cases.len(),
        categories[0],
        categories[1],
        categories[2],
        reason_report.join(" "),
    );
    Ok(())
}

#[test]
fn ownership_corpus_detects_each_declared_checker_mutation() -> Result<(), String> {
    let cases = load_cases();
    let mut report = Vec::new();
    for mutation in MUTATIONS {
        let mut mismatches = 0;
        for case in &cases {
            let outcome = shadow_run(mutation, &case.program, case.operands.as_slice());
            let trace = shadow_trace(mutation, &case.program, case.operands.as_slice());
            if outcome != case.expected || trace != case.trace {
                mismatches += 1;
            }
        }
        if mutation == Mutation::None && mismatches != 0 {
            return Err(format!(
                "the unmutated shadow checker disagrees with {mismatches} retained expectations"
            ));
        }
        if mutation != Mutation::None && mismatches == 0 {
            return Err(format!(
                "mutation {mutation:?} is not caught by any expectation"
            ));
        }
        report.push(format!("{mutation:?}={mismatches}"));
    }
    println!(
        "ownership-mutations cases={} caught=[{}]",
        cases.len(),
        report.join(" ")
    );
    Ok(())
}

#[test]
fn ownership_minimiser_finds_shortest_failing_prefix() -> Result<(), String> {
    // The probe is synthetic so the minimiser is exercised without a live
    // production divergence: it reports a failure only for a `drop`-terminated
    // program over a resource-carrying pair, which is enough to prove that the
    // word list shrinks to its shortest failing prefix and the operand list loses
    // only trailing operands.
    let probe = |words: &[Word], operands: &[Payload]| -> Option<String> {
        let last = words.last().copied();
        let carries_resource = operands.iter().any(Payload::contains_resource);
        if last == Some(Word::Drop) && operands.len() >= 2 && carries_resource {
            Some(format!(
                "word {} refused by the synthetic probe",
                words.len()
            ))
        } else {
            None
        }
    };
    let words = [Word::Dup, Word::Swap, Word::Drop];
    let operands = [
        Payload::Data { tag: 0 },
        Payload::Resource { tag: 1 },
        Payload::Data { tag: 1 },
    ];
    let fixture = minimise_fixture("synthetic", &words, &operands, &probe);
    let expected = "minimised-synthetic ops=dup+swap+drop in=d:0,r:1 divergence=word 3 refused by the synthetic probe";
    if fixture != expected {
        return Err(format!(
            "minimiser returned {fixture:?}, expected {expected:?}"
        ));
    }
    println!("ownership-minimiser fixture={fixture}");
    Ok(())
}

#[test]
fn ownership_minimiser_preserves_model_acceptance() -> Result<(), String> {
    let first = Payload::Data { tag: 0 };
    let second = Payload::Data { tag: 1 };
    let words = [Word::Swap];
    let operands = vec![first.clone(), second.clone()];
    let accepted_trace = shadow_trace_words(Mutation::None, &words, &operands);
    let one_operand_trace =
        shadow_trace_words(Mutation::None, &words, std::slice::from_ref(&first));
    let source_case = Case {
        name: "swap-pair-i64-text".to_string(),
        row: String::new(),
        program: Program::Words(words.to_vec()),
        operands,
        expected: Some(vec![second, first.clone()]),
        trace: Some(accepted_trace.clone()),
        decision: Decision::Accepted,
        reason: None,
    };

    if !candidate_preserves_model_acceptance(&source_case, &words, &accepted_trace) {
        return Err("the full swap control was not kept as model-accepted".to_string());
    }
    if candidate_preserves_model_acceptance(&source_case, &words, &one_operand_trace) {
        return Err(
            "the minimizer allowed an accepted swap control to become an arity refusal".to_string(),
        );
    }
    let (env, maker) = production_environment()?;
    if production_divergence(&env, &source_case, &words, &source_case.operands, maker).is_some() {
        return Err("the production control diverged from its accepted model trace".to_string());
    }
    if production_divergence(
        &env,
        &source_case,
        &words,
        std::slice::from_ref(&first),
        maker,
    )
    .is_some()
    {
        return Err("a model-refused shrink was reported as a production divergence".to_string());
    }
    Ok(())
}
