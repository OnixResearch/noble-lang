//! Ownership accounting corpus lane (issue #59).
//!
//! The expectations in `verification/ownership/cases.txt` are generated by
//! `verification/ownership/cases.mjs` from the Lean model in
//! `proofs/foundation/NobleFoundation/Ownership.lean`, never from this crate.
//!
//! Two things are measured here, and neither is a source-refinement claim:
//!
//! 1. Every case that has a production analogue is driven through the actual
//!    acceptance machine (`noble_kernel::acceptance::check` via
//!    `support::seen`): an accepted case must be accepted with exactly the
//!    model's output stack, and a rejected case must surface as the eligibility
//!    constraint.
//! 2. A test-local shadow checker mirroring the Lean definitions must agree
//!    with every corpus expectation, and each declared mutation of it must be
//!    caught by at least one retained expectation.
//!
//! Cases with no production analogue (wrapped payloads, two-arm accounting, the
//! ordinary error return and the scheme-level swap ordering) are counted and
//! named as model-only; they are never reported as executable production
//! controls.

use std::fs;
use std::path::PathBuf;

use crate::support;

/// The same word fragment the Lean model names.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Word {
    Dup,
    Drop,
    Swap,
    Quote,
}

/// One ordered-stack payload, mirroring `NobleFoundation.Ownership.Payload`.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Payload {
    Data { tag: char },
    Resource { tag: u32 },
    Wrapped { inner: Box<Payload> },
}

impl Payload {
    fn contains_resource(&self) -> bool {
        match self {
            Payload::Wrapped { inner } => inner.contains_resource(),
            Payload::Data { .. } => false,
            Payload::Resource { .. } => true,
        }
    }

    fn duplicable(&self) -> bool {
        !self.contains_resource()
    }
}

#[derive(Clone, Debug)]
enum Program {
    Words(Vec<Word>),
    Branch {
        then_arm: Box<Program>,
        else_arm: Box<Program>,
    },
    Fail,
}

#[derive(Clone, Debug)]
struct Case {
    name: String,
    program: Program,
    operands: Vec<Payload>,
    expected: Option<Vec<Payload>>,
    decision: Decision,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Decision {
    Accepted,
    Rejected,
    ModelOnly,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mutation {
    None,
    ResourceOperandDuplicated,
    ResourceOperandReleased,
    SwapDropsOperand,
    QuoteConsumesOperand,
    BranchPicksThenArm,
    FailAllowsOutstandingOperand,
}

const MUTATIONS: [Mutation; 7] = [
    Mutation::None,
    Mutation::ResourceOperandDuplicated,
    Mutation::ResourceOperandReleased,
    Mutation::SwapDropsOperand,
    Mutation::QuoteConsumesOperand,
    Mutation::BranchPicksThenArm,
    Mutation::FailAllowsOutstandingOperand,
];

fn corpus_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../verification/ownership/cases.txt")
}

fn parse_payload(text: &str) -> Payload {
    if let Some(tag) = text.strip_prefix("d:") {
        return Payload::Data {
            tag: tag.chars().next().unwrap_or('?'),
        };
    }
    if text == "r" {
        return Payload::Resource { tag: 0 };
    }
    if let Some(tag) = text.strip_prefix("r:") {
        return Payload::Resource {
            tag: tag.parse().unwrap_or(0),
        };
    }
    if let Some(inner) = text.strip_prefix("w:") {
        return Payload::Wrapped {
            inner: Box::new(parse_payload(inner)),
        };
    }
    panic!("unknown payload kind {text}");
}

fn parse_words(text: &str) -> Option<Vec<Word>> {
    let mut words = Vec::new();
    for item in text.split('+') {
        words.push(match item {
            "dup" => Word::Dup,
            "drop" => Word::Drop,
            "swap" => Word::Swap,
            "quote" => Word::Quote,
            _ => return None,
        });
    }
    Some(words)
}

fn parse_program(text: &str) -> Program {
    if let Some(inner) = text
        .strip_prefix("branch(")
        .and_then(|rest| rest.strip_suffix(')'))
    {
        let mut parts = inner.splitn(2, '|');
        let then_text = parts.next().unwrap_or_default();
        let else_text = parts.next().unwrap_or_default();
        return Program::Branch {
            then_arm: Box::new(parse_program(then_text)),
            else_arm: Box::new(parse_program(else_text)),
        };
    }
    if text == "fail" {
        return Program::Fail;
    }
    match parse_words(text) {
        Some(words) => Program::Words(words),
        None => panic!("unknown program {text}"),
    }
}

fn parse_operands(text: &str) -> Vec<Payload> {
    if text.is_empty() || text == "empty" {
        return Vec::new();
    }
    text.split(',').map(parse_payload).collect()
}

fn load_cases() -> Vec<Case> {
    let text = fs::read_to_string(corpus_path()).expect("the independent corpus is checked in");
    let mut cases = Vec::new();
    for line in text.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let mut name = String::new();
        let mut program = Program::Fail;
        let mut operands = Vec::new();
        let mut expected: Option<Vec<Payload>> = None;
        let mut decision = Decision::Rejected;
        for field in line.split_whitespace() {
            if let Some(value) = field.strip_prefix("ops=") {
                program = parse_program(value);
            } else if let Some(value) = field.strip_prefix("in=") {
                operands = parse_operands(value);
            } else if let Some(value) = field.strip_prefix("out=") {
                expected = if value == "-" {
                    None
                } else {
                    Some(parse_operands(value))
                };
            } else if let Some(value) = field.strip_prefix("decision=") {
                decision = match value {
                    "accepted" => Decision::Accepted,
                    "rejected" => Decision::Rejected,
                    "model-only" => Decision::ModelOnly,
                    other => panic!("unknown decision {other}"),
                };
            } else {
                name = field.to_string();
            }
        }
        cases.push(Case {
            name,
            program,
            operands,
            expected,
            decision,
        });
    }
    cases
}

/// `NobleFoundation.Ownership.step`, with one declared variation per mutation.
fn shadow_step(mutation: Mutation, word: Word, operands: &[Payload]) -> Option<Vec<Payload>> {
    let mut stack = operands.to_vec();
    let first = stack.first().cloned();
    let second = stack.get(1).cloned();
    match word {
        Word::Dup => {
            let operand = first?;
            let duplicate = mutation == Mutation::ResourceOperandDuplicated || operand.duplicable();
            if !duplicate {
                return None;
            }
            let mut out = stack.clone();
            out.insert(1, operand);
            Some(out)
        }
        Word::Drop => {
            let operand = first?;
            let released = mutation == Mutation::ResourceOperandReleased || operand.duplicable();
            if !released {
                return None;
            }
            stack.remove(0);
            Some(stack)
        }
        Word::Swap => {
            let _ = (first?, second?);
            stack.swap(0, 1);
            if mutation == Mutation::SwapDropsOperand {
                stack.remove(1);
            }
            Some(stack)
        }
        Word::Quote => {
            let operand = first?;
            if !operand.duplicable() {
                return None;
            }
            if mutation == Mutation::QuoteConsumesOperand {
                stack.remove(0);
            }
            Some(stack)
        }
    }
}

/// `NobleFoundation.Ownership.run`, with the same declared variations.
fn shadow_run(mutation: Mutation, program: &Program, operands: &[Payload]) -> Option<Vec<Payload>> {
    match program {
        Program::Words(words) => {
            let mut current = operands.to_vec();
            for word in words {
                current = shadow_step(mutation, *word, current.as_slice())?;
            }
            Some(current)
        }
        Program::Branch { then_arm, else_arm } => {
            let then_out = shadow_run(mutation, then_arm, operands)?;
            let else_out = shadow_run(mutation, else_arm, operands)?;
            if mutation != Mutation::BranchPicksThenArm && then_out != else_out {
                return None;
            }
            Some(then_out)
        }
        Program::Fail => {
            if mutation == Mutation::FailAllowsOutstandingOperand || operands.is_empty() {
                Some(operands.to_vec())
            } else {
                None
            }
        }
    }
}

/// Kernel types for payloads the acceptance machine can name as a binding.
fn kernel_type(payload: &Payload) -> noble_kernel::types::Ty {
    match payload {
        Payload::Data { tag } => {
            if *tag == 't' {
                support::text_ty()
            } else {
                support::i64_ty()
            }
        }
        Payload::Resource { .. } | Payload::Wrapped { .. } => {
            noble_kernel::types::Ty::Resource(noble_kernel::contracts::FIXTURE_RESOURCE)
        }
    }
}

fn word_values(word: Word) -> usize {
    match word {
        Word::Swap => 2,
        Word::Dup | Word::Drop | Word::Quote => 1,
    }
}

fn definition(word: Word) -> noble_kernel::contracts::Definition {
    noble_kernel::contracts::Definition(match word {
        Word::Dup => 0,
        Word::Drop => 1,
        Word::Swap => 2,
        Word::Quote => 8,
    })
}

/// Pushes one operand payload onto the derived stack.
fn push_node(
    payload: &Payload,
    maker: noble_kernel::contracts::Definition,
) -> noble_kernel::untrusted::Node {
    match payload {
        Payload::Data { tag } => {
            if *tag == 't' {
                support::lit_node(noble_kernel::untrusted::Lit::Text, vec![])
            } else {
                support::lit_node(noble_kernel::untrusted::Lit::I64(0), vec![])
            }
        }
        Payload::Resource { .. } | Payload::Wrapped { .. } => {
            support::invocation(maker, vec![support::segment(vec![])])
        }
    }
}

/// The production analogue of one corpus case: the operands are pushed in
/// reverse order so the model's head is the top of the stack, then one
/// invocation per word consumes and re-derives them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum ProductionCategory {
    NotDriven,
    Accepted,
    Eligibility,
    StackJoin,
    OtherRejection,
}

fn drive_production(case: &Case) -> Result<ProductionCategory, String> {
    if case.decision == Decision::ModelOnly {
        return Ok(ProductionCategory::NotDriven);
    }
    let Program::Words(words) = &case.program else {
        return Err(format!("{} has no word-sequence analogue", case.name));
    };
    if case.operands.is_empty() {
        return Err(format!("{} names no operand", case.name));
    }
    let mut env = noble_kernel::contracts::environment().map_err(|defect| format!("{defect:?}"))?;
    let maker = noble_kernel::contracts::Definition(23);
    env.defs.push(noble_kernel::words::Scheme {
        var_kinds: vec![noble_kernel::words::VariableKind::Stack],
        stack_in: vec![noble_kernel::shapes::Pattern::StackVar(
            noble_kernel::words::Variable(0),
        )],
        stack_out: vec![
            noble_kernel::shapes::Pattern::StackVar(noble_kernel::words::Variable(0)),
            noble_kernel::shapes::Pattern::Resource(noble_kernel::contracts::FIXTURE_RESOURCE),
        ],
        effects: vec![],
    });
    env.kinds.push(noble_kernel::contracts::Behavior::Named);
    env.deps.push(Vec::new());
    let mut nodes = Vec::new();
    for operand in case.operands.iter().rev() {
        nodes.push(push_node(operand, maker));
    }
    for word in words {
        let mut bindings = vec![support::segment(vec![])];
        let operand = case
            .operands
            .first()
            .ok_or_else(|| format!("{} names no operand", case.name))?;
        bindings.push(support::value(kernel_type(operand)));
        if *word == Word::Quote {
            // The quote scheme names its produced program's segment after the
            // quoted value, so the invocation binds an empty segment twice.
            bindings.push(support::segment(vec![]));
        }
        if word_values(*word) == 2 {
            // The production scheme binds the deeper operand first, so the
            // model's second operand occupies the first value slot.
            let second = case
                .operands
                .get(1)
                .ok_or_else(|| format!("{} names one operand for a pair", case.name))?;
            bindings.insert(1, support::value(kernel_type(second)));
        }
        nodes.push(support::invocation(definition(*word), bindings));
    }
    let expected: Vec<noble_kernel::types::Ty> = case
        .expected
        .as_ref()
        .map(|payloads| payloads.iter().rev().map(kernel_type).collect())
        .unwrap_or_default();
    let candidate = support::candidate(
        nodes,
        (0..(case.operands.len() + words.len()) as u32).collect(),
    );
    let request = support::request(vec![], expected.clone(), &[]);
    match case.decision {
        Decision::Accepted => match support::seen(&env, &request, &candidate)? {
            support::Seen::Accepted(checked) => {
                if checked.interface.stack_out != expected {
                    return Err(format!(
                        "{} accepted with {:?} instead of the model's {:?}",
                        case.name, checked.interface.stack_out, expected
                    ));
                }
                Ok(ProductionCategory::Accepted)
            }
            support::Seen::Bad(diagnostic) => Err(format!(
                "{} rejected ({:?}) expected {:?} actual {:?}",
                case.name, diagnostic.constraint, diagnostic.expected, diagnostic.actual
            )),
            support::Seen::Exhausted(limit) => Err(format!("{} exhausted {limit:?}", case.name)),
        },
        Decision::Rejected => match support::seen(&env, &request, &candidate)? {
            support::Seen::Accepted(_) => {
                Err(format!("{} accepted but the model rejects it", case.name))
            }
            support::Seen::Bad(diagnostic) => {
                // Both sides reject, so the accounting decision agrees. The
                // production rejection category is the machine's own: a
                // resource payload can fail the stack join before eligibility is
                // reached, so categories are reported rather than pinned.
                let category = match diagnostic.constraint {
                    noble_kernel::untrusted::Constraint::Eligibility(_) => {
                        ProductionCategory::Eligibility
                    }
                    noble_kernel::untrusted::Constraint::StackJoin => ProductionCategory::StackJoin,
                    _ => ProductionCategory::OtherRejection,
                };
                Ok(category)
            }
            support::Seen::Exhausted(limit) => Err(format!("{} exhausted {limit:?}", case.name)),
        },
        Decision::ModelOnly => Ok(ProductionCategory::NotDriven),
    }
}

#[test]
fn ownership_corpus_matches_the_acceptance_machine() -> Result<(), String> {
    let cases = load_cases();
    let mut accepted = 0;
    let mut rejected = 0;
    let mut model_only = 0;
    let mut eligibility = 0;
    let mut stack_join = 0;
    let mut other_rejection = 0;
    for case in &cases {
        match case.decision {
            Decision::Accepted => accepted += 1,
            Decision::Rejected => rejected += 1,
            Decision::ModelOnly => model_only += 1,
        }
        match drive_production(case)? {
            ProductionCategory::Eligibility => eligibility += 1,
            ProductionCategory::StackJoin => stack_join += 1,
            ProductionCategory::OtherRejection => other_rejection += 1,
            ProductionCategory::Accepted | ProductionCategory::NotDriven => {}
        }
    }
    if accepted < 12 || rejected < 5 || model_only < 60 {
        return Err(format!(
            "corpus coverage regressed: accepted={accepted} rejected={rejected} model-only={model_only}"
        ));
    }
    if eligibility == 0 {
        return Err("no accepted case surfaced the eligibility constraint".to_string());
    }
    if eligibility + stack_join + other_rejection != rejected {
        return Err(format!(
            "rejected cases {rejected} but categories total {}",
            eligibility + stack_join + other_rejection
        ));
    }
    println!(
        "ownership-differential cases={} accepted={accepted} rejected={rejected} model-only={model_only} categories=eligibility:{eligibility} stack-join:{stack_join} other:{other_rejection}",
        cases.len()
    );
    Ok(())
}

#[test]
fn ownership_corpus_detects_each_declared_checker_mutation() -> Result<(), String> {
    let cases = load_cases();
    let mut report = Vec::new();
    for mutation in MUTATIONS {
        let mut mismatches = 0;
        for case in &cases {
            let outcome = shadow_run(mutation, &case.program, case.operands.as_slice());
            if outcome != case.expected {
                mismatches += 1;
            }
        }
        if mutation == Mutation::None && mismatches != 0 {
            return Err(format!(
                "the unmutated shadow checker disagrees with {mismatches} retained expectations"
            ));
        }
        if mutation != Mutation::None && mismatches == 0 {
            return Err(format!(
                "mutation {mutation:?} is not caught by any expectation"
            ));
        }
        report.push(format!("{mutation:?}={mismatches}"));
    }
    println!(
        "ownership-mutations cases={} caught=[{}]",
        cases.len(),
        report.join(" ")
    );
    Ok(())
}
