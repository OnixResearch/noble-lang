// Reproduce and bind one dynamic-input production artifact for issue #82.
// This script deliberately separates one-time source-file creation from clean-commit receipt replay.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { createReadStream, existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const lane = join(root, 'verification/wasm-refinement-pilot');
const sourcePath = join(lane, 'mul.noble');
const selection = JSON.parse(readFileSync(join(root, 'policy/tool-selection.json'), 'utf8'));
const nodePath = join(selection.tool_paths.node.output, 'bin/node');
const wasmTools = join(selection.tool_paths.wasm_tools.output, 'bin/wasm-tools');
const git = realpathSync('/run/current-system/sw/bin/git');
const fail = message => { throw new Error(message); };
const requireThat = (condition, message) => { if (!condition) fail(message); };
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

async function hashFile(path) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(path)) hash.update(chunk);
  return hash.digest('hex');
}

function run(command, args, cwd = root) {
  const result = spawnSync(command, args, { cwd, env: {}, encoding: null, maxBuffer: 128 * 1024 * 1024 });
  requireThat(result.error === undefined, `${command} ${args[0]}: ${result.error}`);
  requireThat(result.status === 0, `${command} ${args[0]} failed: ${result.stderr.toString('utf8')}`);
  return result.stdout;
}

function leanString(value) {
  return JSON.stringify(value);
}

function generatedSubject({ artifactSha256, textSha256, sourceSha256, compilerSha256, printed }) {
  const wat = printed.toString('utf8');
  requireThat(Buffer.from(wat, 'utf8').equals(printed), 'wasm-tools output is not round-trippable UTF-8');
  requireThat(!wat.includes('\r'), 'unexpected carriage return in wasm-tools output');
  return [
    '-- Generated by verification/wasm-refinement-pilot/emit-mul.mjs; do not edit.',
    'namespace Interpreter.WasmPilot.SubjectMul',
    '',
    `def artifactSha256 : String := ${leanString(artifactSha256)}`,
    `def textSha256 : String := ${leanString(textSha256)}`,
    `def sourceSha256 : String := ${leanString(sourceSha256)}`,
    `def compilerSha256 : String := ${leanString(compilerSha256)}`,
    `def wat : String := ${leanString(wat)}`,
    '',
    'end Interpreter.WasmPilot.SubjectMul',
    '',
  ].join('\n');
}

async function main() {
  const [mode, ...args] = process.argv.slice(2);
  requireThat(mode === '--write-subject' || mode === '--verify-subject',
    'usage: emit-mul.mjs (--write-subject|--verify-subject) --work-dir ABS_PATH --noble ABS_PATH --output NEW_DIR_OUTSIDE_REPOSITORY');
  const options = Object.fromEntries(args.reduce((pairs, arg, index) => {
    if (arg === '--work-dir' || arg === '--noble' || arg === '--output') pairs.push([arg, args[index + 1]]);
    return pairs;
  }, []));
  requireThat(options['--work-dir'] && options['--noble'] && options['--output'] && args.length === 6,
    'missing or unexpected arguments');
  requireThat(realpathSync(process.execPath) === realpathSync(nodePath), 'process is not the policy-selected Node executable');
  const forbidden = Object.keys(process.env).filter(key => process.env[key] !== '');
  requireThat(forbidden.length === 0, `refusing ambient environment variables: ${forbidden.join(', ')}`);
  const noble = realpathSync(options['--noble']);
  const workDir = resolve(options['--work-dir']);
  requireThat(isAbsolute(options['--work-dir']) && workDir !== root && !workDir.startsWith(`${root}/`),
    '--work-dir must be an absolute path outside the repository');
  const prepared = JSON.parse(readFileSync(join(workDir, 'talos-source.json'), 'utf8'));
  requireThat(prepared.schema === 'wasm-pilot-talos-preparation/v1' &&
    prepared.upstream_commit === 'd7c84ac660757953b752bdfc9cb8dae3dab623ed' && /^[0-9a-f]{40}$/.test(prepared.upstream_tree),
    'work directory does not contain the required pinned Talos preparation receipt');
  const subjectPath = join(workDir, 'interpreter/Interpreter/WasmPilot/SubjectMul.lean');
  const output = resolve(options['--output']);
  requireThat(output !== root && !output.startsWith(`${root}/`), 'output directory must be outside the repository');
  const sourceCommit = run(git, ['rev-parse', 'HEAD']).toString('utf8').trim();
  const status = run(git, ['status', '--porcelain']).toString('utf8').trim();
  requireThat(status === '', `receipts require a clean committed source tree; status=${JSON.stringify(status)}`);
  requireThat(prepared.source_commit === sourceCommit, 'prepared project belongs to a different Noble source commit');
  mkdirSync(output);
  const work = join(output, 'work');
  mkdirSync(work);
  const sourceBytes = readFileSync(sourcePath);
  const sourceSha256 = sha256(sourceBytes);
  const expectedSource = Buffer.from('*');
  requireThat(sourceBytes.equals(expectedSource), 'mul.noble changed from the reviewed one-token `*` source');
  const compilerSha256 = await hashFile(noble);
  const compilerArgs = ['compile', sourcePath, '--input-type', 'I64', '--input-type', 'I64'];
  const printed = run(noble, compilerArgs);
  const watPath = join(work, 'mul.wat');
  const wasmPath = join(work, 'mul.wasm');
  writeFileSync(watPath, printed, { flag: 'wx' });
  run(wasmTools, ['parse', watPath, '-o', wasmPath], work);
  run(wasmTools, ['validate', wasmPath], work);
  const bytes = readFileSync(wasmPath);
  const artifactSha256 = sha256(bytes);
  const textSha256 = sha256(printed);
  const roundTripPath = join(work, 'roundtrip.wasm');
  run(wasmTools, ['parse', watPath, '-o', roundTripPath], work);
  const roundTripped = readFileSync(roundTripPath);
  requireThat(roundTripped.equals(bytes), 'wasm-tools parse was not deterministic on the emitted WAT');
  const subjectBytes = Buffer.from(generatedSubject({ artifactSha256, textSha256, sourceSha256, compilerSha256, printed }), 'utf8');
  if (mode === '--write-subject') {
    requireThat(!existsSync(subjectPath), 'SubjectMul.lean already exists; use --verify-subject');
    writeFileSync(subjectPath, subjectBytes, { flag: 'wx' });
  } else {
    requireThat(existsSync(subjectPath), 'SubjectMul.lean is missing; use --write-subject from a clean commit');
    requireThat(readFileSync(subjectPath).equals(subjectBytes), 'emitted artifact differs from committed SubjectMul.lean');
  }
  const receipt = {
    schema: 'wasm-pilot-emission/v1',
    mode,
    source_commit: sourceCommit,
    source_worktree_clean: true,
    source_path: 'verification/wasm-refinement-pilot/mul.noble',
    source_sha256: sourceSha256,
    compiler_path: noble,
    compiler_sha256: compilerSha256,
    compiler_args: compilerArgs,
    node_path: realpathSync(process.execPath),
    node_version: process.version,
    v8_version: process.versions.v8,
    wasm_tools_path: wasmTools,
    wasm_tools_version: run(wasmTools, ['--version']).toString('utf8').trim(),
    artifact_bytes: bytes.length,
    artifact_sha256: artifactSha256,
    wat_bytes: printed.length,
    wat_sha256: textSha256,
    subject_file_sha256: sha256(subjectBytes),
    talos_source_commit: prepared.upstream_commit,
    talos_source_tree: prepared.upstream_tree,
  };
  writeFileSync(join(output, 'emission.json'), `${JSON.stringify(receipt, null, 2)}\n`, { flag: 'wx' });
  process.stdout.write(`[wasm-pilot-emission] PASS mode=${mode} commit=${sourceCommit} bytes=${bytes.length} sha256=${artifactSha256}\n`);
}

main().catch(error => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
