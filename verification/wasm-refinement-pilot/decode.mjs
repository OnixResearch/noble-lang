// Issue #82: bind Talos's verification decoder input to the retained subject
// bytes. The external wasm-tools text representation is trusted only after a
// binary round-trip reproduces the exact source bytes.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const artifact = 'verification/owi/receipts/2026-10-26/subject-module-1.wasm';
const sums = 'verification/owi/receipts/2026-10-26/sha256sums.txt';
const fail = message => { throw new Error(message); };
const requireThat = (condition, message) => { if (!condition) fail(message); };
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

function run(command, args, cwd = root) {
  const result = spawnSync(command, args, {
    cwd,
    env: {},
    encoding: null,
    maxBuffer: 128 * 1024 * 1024,
  });
  requireThat(result.error === undefined, `${path.basename(command)} ${args[0]}: ${result.error}`);
  requireThat(result.status === 0, `${path.basename(command)} ${args[0]} failed: ${result.stderr.toString('utf8')}`);
  return result.stdout;
}

function leanString(value) {
  return JSON.stringify(value);
}

function subjectModule(byteDigest, textDigest, printed) {
  const wat = printed.toString('utf8');
  requireThat(Buffer.from(wat, 'utf8').equals(printed), 'wasm-tools print output is not round-trippable UTF-8');
  requireThat(!wat.includes('\r'), 'unexpected carriage return in wasm-tools print output');
  return [
    '-- Generated by verification/wasm-refinement-pilot/decode.mjs; do not edit.',
    'namespace Interpreter.WasmPilot.Subject',
    '',
    `def artifactSha256 : String := ${leanString(byteDigest)}`,
    `def textSha256 : String := ${leanString(textDigest)}`,
    `def wat : String := ${leanString(wat)}`,
    '',
    'end Interpreter.WasmPilot.Subject',
    '',
  ].join('\n');
}

function main() {
  const args = process.argv.slice(2);
  requireThat((args.length === 4 && args[0] === '--work-dir' && args[1] !== '' && args[2] === '--output' && args[3] !== '') ||
    (args.length === 6 && args[0] === '--work-dir' && args[1] !== '' && args[2] === '--output' && args[3] !== '' &&
      args[4] === '--artifact-bytes' && args[5] !== ''),
    'usage: decode.mjs --work-dir ABS_PATH --output <new directory outside repository> [--artifact-bytes ABS_PATH]');
  const forbidden = Object.keys(process.env).filter(key =>
    /^(?:NODE_OPTIONS|NODE_PATH|LD_|DYLD_|ENV$)/.test(key) && process.env[key] !== '');
  requireThat(forbidden.length === 0, `refusing ambient execution variables: ${forbidden.join(', ')}`);

  const workDir = path.resolve(args[1]);
  requireThat(path.isAbsolute(args[1]) && workDir !== root && !workDir.startsWith(`${root}${path.sep}`),
    '--work-dir must be an absolute path outside the repository');
  const project = path.join(workDir, 'interpreter');
  const prepared = JSON.parse(fs.readFileSync(path.join(workDir, 'talos-source.json'), 'utf8'));
  requireThat(prepared.schema === 'wasm-pilot-talos-preparation/v1' &&
    prepared.upstream_commit === 'd7c84ac660757953b752bdfc9cb8dae3dab623ed' && /^[0-9a-f]{40}$/.test(prepared.upstream_tree),
    'work directory does not contain the required pinned Talos preparation receipt');
  const subjectSource = path.join(project, 'Interpreter/WasmPilot/Subject.lean');
  const output = path.resolve(args[3]);
  const artifactSource = args.length === 6 ? path.resolve(args[5]) : path.join(root, artifact);
  requireThat(output !== root && !output.startsWith(`${root}${path.sep}`), 'output directory must be outside the repository');
  const git = '/run/current-system/sw/bin/git';
  const sourceCommit = run(git, ['rev-parse', 'HEAD']).toString('utf8').trim();
  const treeStatus = run(git, ['status', '--porcelain']).toString('utf8').trim();
  requireThat(prepared.source_commit === sourceCommit, 'prepared project belongs to a different Noble source commit');
  requireThat(treeStatus === '', `receipts require a clean committed source tree: ${JSON.stringify(treeStatus)}`);
  fs.mkdirSync(output);
  const work = path.join(output, 'roundtrip');
  fs.mkdirSync(work);

  const selection = JSON.parse(fs.readFileSync(path.join(root, 'policy/tool-selection.json'), 'utf8'));
  const wasmTools = path.join(selection.tool_paths.wasm_tools.output, 'bin/wasm-tools');
  const bytes = fs.readFileSync(artifactSource);
  const byteDigest = sha256(bytes);
  const expected = fs.readFileSync(path.join(root, sums), 'utf8').split('\n')
    .map(line => line.match(/^([0-9a-f]{64})\s+(.+)$/))
    .find(match => match?.[2] === artifact)?.[1];
  requireThat(expected === byteDigest, `subject sha256 ${byteDigest} does not match retained sha256 ${expected ?? '(missing)'}`);

  const printed = run(wasmTools, ['print', artifactSource]);
  const textDigest = sha256(printed);
  const watPath = path.join(work, 'subject.wat');
  const roundTripPath = path.join(work, 'roundtrip.wasm');
  fs.writeFileSync(watPath, printed, { flag: 'wx' });
  run(wasmTools, ['parse', watPath, '-o', roundTripPath], work);
  const roundTripped = fs.readFileSync(roundTripPath);
  requireThat(roundTripped.length === bytes.length, `round-trip size ${roundTripped.length} != source size ${bytes.length}`);
  requireThat(roundTripped.equals(bytes), `round-trip sha256 ${sha256(roundTripped)} differs from source ${byteDigest}`);

  const generated = Buffer.from(subjectModule(byteDigest, textDigest, printed), 'utf8');
  fs.mkdirSync(path.dirname(subjectSource), { recursive: true });
  fs.writeFileSync(subjectSource, generated);
  const receipt = {
    schema: 'noble-wasm-pilot-decode/v1',
    issue: 82,
    source_commit: sourceCommit,
    clean_tree_at_start: treeStatus === '',
    artifact,
    artifact_bytes_path: artifactSource,
    artifact_sha256: byteDigest,
    artifact_bytes: bytes.length,
    decoder: run(wasmTools, ['--version']).toString('utf8').trim(),
    printed_text_sha256: textDigest,
    printed_text_bytes: printed.length,
    roundtrip_bytes: roundTripped.length,
    roundtrip_sha256: sha256(roundTripped),
    generated_subject_source_sha256: sha256(generated),
    generated_subject_source: path.join(project, 'Interpreter/WasmPilot/Subject.lean'),
    talos_source_commit: prepared.upstream_commit,
    talos_source_tree: prepared.upstream_tree,
    method: 'wasm-tools print, then wasm-tools parse, followed by exact byte-for-byte equality against the retained artifact',
  };
  fs.writeFileSync(path.join(output, 'decode.json'), `${JSON.stringify(receipt, null, 2)}\n`, { flag: 'wx' });
  fs.rmSync(work, { recursive: true, force: true });
  process.stdout.write(`[wasm-pilot-decode] PASS bytes=${bytes.length} sha256=${byteDigest} text_sha256=${textDigest} roundtrip=exact\n`);
}

try {
  main();
} catch (error) {
  console.error(`[wasm-pilot-decode] FAIL ${error.message}`);
  process.exitCode = 1;
}
