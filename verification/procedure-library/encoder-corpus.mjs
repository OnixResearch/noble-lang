#!/usr/bin/env node
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const MODEL = 'proofs/foundation/NobleFoundation/ProcedureLibraryWire.lean';
const EMITTER = 'verification/procedure-library/encoder-corpus.lean';
const RUNNER = 'verification/procedure-library/encoder-corpus.mjs';
const RUST_ENCODER = 'crates/noble-contracts/src/source/procedures/persistence.rs';
const RUST_API = 'crates/noble-contracts/src/source/procedures.rs';
const RUST_FIXTURE = 'crates/noble-contracts/tests/editor/procedures/transfer/producer.rs';
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const sourceDigest = relative => digest(fs.readFileSync(path.join(ROOT, relative)));

function args() {
  const values = process.argv.slice(2);
  assert.equal(values.length, 4, 'usage: encoder-corpus.mjs --lean ABS (--output ABS | --verify ABS)');
  const result = {};
  for (let index = 0; index < values.length; index += 2) {
    assert.ok(['--lean', '--output', '--verify'].includes(values[index]) && !(values[index] in result));
    assert.ok(path.isAbsolute(values[index + 1]));
    result[values[index]] = values[index + 1];
  }
  assert.ok(result['--lean']);
  assert.notEqual(Boolean(result['--output']), Boolean(result['--verify']));
  if (result['--output']) {
    assert.ok(!fs.existsSync(result['--output']), 'new corpus output must not exist');
    assert.ok(!result['--output'].startsWith(ROOT + path.sep), 'new corpus must be written outside the source tree');
  }
  return result;
}

function git(parameters) {
  const result = spawnSync('git', parameters, { cwd: ROOT, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
}

function emit(lean) {
  const result = spawnSync(lean,
    [path.join(ROOT, 'proofs/foundation'), 'env', 'lean', '--run', path.join(ROOT, EMITTER)],
    { cwd: ROOT, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024, timeout: 10 * 60 * 1000 });
  assert.equal(result.status, 0, result.error?.message ?? result.stderr);
  const lines = result.stdout.split('\n').filter(line => line.trim().startsWith('{'));
  assert.equal(lines.length, 1, 'Lean corpus emitter must print exactly one JSON line');
  const corpus = JSON.parse(lines[0]);
  assert.equal(corpus.schema, 'noble-procedure-library-lean-byte-corpus/1');
  assert.equal(corpus.cases.length, 2);
  return { corpus, stdout_sha256: digest(result.stdout), stderr_sha256: digest(result.stderr) };
}

function main() {
  const options = args();
  const source = {
    model_sha256: sourceDigest(MODEL),
    emitter_sha256: sourceDigest(EMITTER),
    runner_sha256: sourceDigest(RUNNER),
    rust_encoder_sha256: sourceDigest(RUST_ENCODER),
    rust_api_sha256: sourceDigest(RUST_API),
    rust_fixture_sha256: sourceDigest(RUST_FIXTURE),
  };
  const emission = emit(options['--lean']);
  if (options['--verify']) {
    const retained = JSON.parse(fs.readFileSync(options['--verify'], 'utf8'));
    assert.equal(retained.schema, 'noble-procedure-library-lean-byte-receipt/1');
    assert.deepEqual(retained.source, source, 'corpus source or Rust encoder drifted');
    assert.deepEqual(retained.corpus, emission.corpus, 'retained Lean-generated bytes drifted');
    process.stdout.write(`${JSON.stringify({ result: 'passed', cases: retained.corpus.cases.length,
      producer_commit: retained.producer_commit, source })}\n`);
    return;
  }
  assert.equal(git(['status', '--porcelain', '--untracked-files=all']), '', 'corpus producer must run from a clean source commit');
  const receipt = {
    schema: 'noble-procedure-library-lean-byte-receipt/1',
    producer_commit: git(['rev-parse', 'HEAD']),
    producer_tree: git(['rev-parse', 'HEAD^{tree}']),
    lean_version: '4.35.0 (pinned foundation toolchain)',
    source,
    stdout_sha256: emission.stdout_sha256,
    stderr_sha256: emission.stderr_sha256,
    corpus: emission.corpus,
    scope: 'Finite no-capture/no-dependency, one-empty-instantiation I64 source records: one Synthesis and one Chunk provenance.',
    correspondence_obligation: 'A universal refinement of all accepted Rust subject encodings, all chunk variants, the experimental digest and exact #56 pair certificates remains unproved. The separate Rust differential test compares only the two emitted fixtures.',
  };
  fs.writeFileSync(options['--output'], `${JSON.stringify(receipt, null, 2)}\n`, { flag: 'wx', mode: 0o600 });
  process.stdout.write(`${JSON.stringify({ output: options['--output'], producer_commit: receipt.producer_commit,
    model_sha256: source.model_sha256, rust_encoder_sha256: source.rust_encoder_sha256,
    cases: receipt.corpus.cases.length })}\n`);
}

main();
