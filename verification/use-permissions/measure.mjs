// Measures the issue #112 worked cases in the *selected* source profile. It never edits a form
// between runs and never claims one form's numbers for another form.
//
// For every `.noble` form it records:
//   * authored source size: bytes, whitespace tokens, and how many tokens are permission words
//     (`dup`, `drop`, `swap`, `dip`, `quote`, `compose`, `run`), which is the authoring surface the
//     issue asks about;
//   * checking cost: wall time of `noble compile --opt off` over `--runs` runs after a warm-up,
//     the exit status and the generated module `compile` printed (bytes, lines, sha256);
//   * executed shape: `noble live repl` metrics and the resulting stack, so the value each case
//     computes is recorded rather than asserted.
//
// What it does NOT measure: the *proposed* four-way permission profile. No source syntax carries a
// separate duplicate or discard permission and the selected profile has no must-use resource word,
// so the proposed-profile rows exist only in the lane README, `decision.md` and the Lean model
// `proofs/foundation/NobleFoundation/UsePermissions.lean`. Timing a form that cannot be compiled
// would be inventing data.
//
// The receipt binds the exact source commit and tree it ran on, refuses a dirty tracked tree, and
// records the digest of the independent expectation corpus (`cases.txt`, generated by `cases.mjs`)
// it ran beside.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const option = (name, fallback) => {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : fallback;
};

const noble = resolve(option('--noble', join(root, 'result/bin/noble')));
const forms = resolve(option('--forms', join(here, 'forms')));
const output = resolve(option('--output', join(here, 'receipts', 'measure.json')));
const runs = Number(option('--runs', '7'));
const optimize = option('--opt', 'off');
const casesFile = join(here, 'cases.txt');

if (!Number.isInteger(runs) || runs < 1) {
  console.error(`--runs must be a positive integer, got ${runs}`);
  process.exit(2);
}

if (!existsSync(noble)) {
  console.error(`noble binary not found: ${noble}`);
  process.exit(2);
}

const permissionWords = new Set([
  'dup', 'drop', 'swap', 'dip', 'quote', 'compose', 'run',
]);

const words = source => source.split(/\s+/).filter(token => token.length > 0);

const median = values => {
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
};

const round = value => Math.round(value * 1000) / 1000;

const sha256File = path => createHash('sha256').update(readFileSync(path)).digest('hex');

const git = args =>
  spawnSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });

const head = git(['rev-parse', 'HEAD']);
if (head.status !== 0) {
  console.error(`git rev-parse failed: ${head.stderr}`);
  process.exit(2);
}
const tree = git(['rev-parse', 'HEAD^{tree}']);
if (tree.status !== 0) {
  console.error(`git rev-parse tree failed: ${tree.stderr}`);
  process.exit(2);
}
const status = git(['status', '--porcelain=v1', '--untracked-files=all']);
if (status.status !== 0) {
  console.error(`git status failed: ${status.stderr}`);
  process.exit(2);
}
if (status.stdout.trim().length > 0) {
  console.error(`the lane receipt requires a clean tracked tree:\n${status.stdout}`);
  process.exit(2);
}
if (!existsSync(casesFile) || readFileSync(casesFile, 'utf8').trim().length === 0) {
  console.error(`expectation corpus is missing or empty: ${casesFile}`);
  process.exit(2);
}

const expectedStacks = {
  'control-harmless-duplication': [{ type: 'I64', value: '14' }],
  'discarded-intermediate': [{ type: 'I64', value: '4' }],
  'must-handle-candidate': [],
  'shared-configuration': [{ type: 'I64', value: '4' }],
};

const measure = file => {
  const source = readFileSync(file, 'utf8');
  const tokens = words(source);
  const runOnce = () => {
    const started = process.hrtime.bigint();
    const result = spawnSync(noble, ['compile', file, '--opt', optimize], {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
    const ended = process.hrtime.bigint();
    return {
      milliseconds: Number(ended - started) / 1e6,
      status: result.status,
      stdout: result.stdout ?? '',
      stderr: (result.stderr ?? '').trim(),
    };
  };
  const warm = runOnce();
  if (warm.status !== 0) {
    throw new Error(`${file}: warm compile failed (${warm.status}): ${warm.stderr}`);
  }
  const times = [];
  let last = warm;
  for (let run = 0; run < runs; run += 1) {
    last = runOnce();
    if (last.status !== 0) {
      throw new Error(`${file}: compile run ${run + 1} failed (${last.status}): ${last.stderr}`);
    }
    times.push(last.milliseconds);
  }
  const module = last.stdout;
  if (module.length === 0) {
    throw new Error(`${file}: successful compile produced an empty module`);
  }
  const live = spawnSync(noble, ['live', 'repl'], {
    input: source,
    encoding: 'utf8',
    timeout: 300_000,
    maxBuffer: 64 * 1024 * 1024,
  });
  if (live.status !== 0) {
    throw new Error(`${file}: noble live repl failed (${live.status}): ${(live.stderr ?? '').trim()}`);
  }
  const lines = (live.stdout ?? '').split('\n').filter(line => line.length > 0);
  const lastReport = lines.at(-1);
  if (!lastReport) {
    throw new Error(`${file}: noble live repl produced no JSON report`);
  }
  let report;
  try {
    report = JSON.parse(lastReport);
  } catch (error) {
    throw new Error(`${file}: final live repl line is not JSON: ${error.message}`);
  }
  if (report.schema !== 'noble-core-report/v1' || report.status !== 0 ||
      report.metrics?.status !== 0 || report.outcome !== 'normal') {
    throw new Error(`${file}: live repl did not complete normally: ${lastReport}`);
  }
  const observedStack = report.stack.map(({ type, value }) => ({ type, value }));
  const form = file.split('/').pop().replace(/\.noble$/, '');
  if (!(form in expectedStacks) ||
      JSON.stringify(observedStack) !== JSON.stringify(expectedStacks[form])) {
    throw new Error(`${file}: expected stack ${JSON.stringify(expectedStacks[form])}, got ${JSON.stringify(observedStack)}`);
  }
  const executed = {
    status: report.metrics.status,
    stack: report.stack,
    executionSteps: report.metrics.execution_steps,
    quoteInvocations: report.metrics.quote_invocations,
    allocatedTotalBytes: report.metrics.allocated_total_bytes,
    operandPeakBytes: report.metrics.operand_peak_bytes,
    continuationPeakBytes: report.metrics.continuation_peak_bytes,
    reflectionSteps: report.metrics.reflection_steps,
  };
  return {
    form,
    path: file.slice(root.length + 1),
    authored: {
      bytes: Buffer.byteLength(source),
      tokens: tokens.length,
      permissionTokens: tokens.filter(token => permissionWords.has(token)).length,
      quotations: (source.match(/\[/g) ?? []).length,
    },
    compile: {
      opt: optimize,
      runs,
      status: last.status,
      stderr: last.stderr,
      medianMilliseconds: round(median(times)),
      minMilliseconds: round(Math.min(...times)),
      maxMilliseconds: round(Math.max(...times)),
      warmupMilliseconds: round(warm.milliseconds),
      moduleBytes: Buffer.byteLength(module),
      moduleLines: module.split('\n').length - 1,
      moduleSha256: createHash('sha256').update(module).digest('hex'),
    },
    executed,
  };
};

const cases = readdirSync(forms).filter(name => name.endsWith('.noble')).sort();
if (JSON.stringify(cases) !== JSON.stringify(Object.keys(expectedStacks).map(name => `${name}.noble`).sort())) {
  throw new Error(`unexpected source forms: ${cases.join(', ')}`);
}
const results = cases.map(name => measure(join(forms, name)));
mkdirSync(dirname(output), { recursive: true });
const receipt = {
  schema: 'noble-use-permissions-measure/v1',
  assertion: 'the four worked cases of issue #112 compile and run in the selected source profile on this host, with the values and costs recorded here; no four-way permission profile is measured because no source form carries one',
  source_commit: head.stdout.trim(),
  source_tree: tree.stdout.trim(),
  clean_source: true,
  noble,
  nobleSha256: sha256File(noble),
  host: `${process.platform} ${process.arch}`,
  opt: optimize,
  runs,
  formsDirectory: forms.slice(root.length + 1),
  expectationCorpus: {
    path: casesFile.slice(root.length + 1),
    sha256: existsSync(casesFile) ? sha256File(casesFile) : null,
  },
  results,
};
writeFileSync(output, `${JSON.stringify(receipt, null, 2)}\n`);
for (const result of results) {
  process.stdout.write(`${JSON.stringify({
    form: result.form,
    compile: result.compile.status,
    medianMilliseconds: result.compile.medianMilliseconds,
    steps: result.executed?.executionSteps ?? null,
    stack: result.executed?.stack?.length ?? null,
  })}\n`);
}
process.stdout.write(`${JSON.stringify({ receipt: output })}\n`);
